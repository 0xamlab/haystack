#!/usr/bin/env bash
# build_tc_probe.sh — build the NVIDIA tensor-core escape-hatch probe ON A GPU VM:
# nvcc-compiles tc_shim.cu (cuBLAS HMMA + WMMA + packed3 dequant) for the local GPU's sm
# target, then builds tc_escape_probe.mojo and links the shim object into the Mojo CUDA
# binary. Two link recipes, tried in order (both recorded in the ledger):
#   1. plain `mojo build ... -Xlinker tc_shim.o -Xlinker -lcublas -Xlinker -lcudart`
#      (the exact CUDA analog of the Metal lane's `-Xlinker batch_shim.o` recipe)
#   2. `mojo build --emit object` + external clang link with the MAX runtime libs
#      (setup_vm.sh's build_one_driver fallback) + the CUDA libs appended.
#
# Usage (on algenta-ent-h100 / algenta-ent-a100, repo root = ~/algenta or a worktree):
#   bash scripts/build_tc_probe.sh            # auto-detects sm target from nvidia-smi
#   SM_TARGET=sm_80 bash scripts/build_tc_probe.sh
#   OUT_DIR=/tmp/tc_probe CUDA_HOME=/usr/local/cuda bash scripts/build_tc_probe.sh
#
# Run the result (GPU 0, keep the census solo):
#   CUDA_VISIBLE_DEVICES=0 /tmp/tc_probe/tc_escape_probe
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="${OUT_DIR:-/tmp/tc_probe}"
CUDA_HOME="${CUDA_HOME:-/usr/local/cuda}"
ENV_DIR="$REPO_ROOT/mojo_env/.pixi/envs/default"
MOJO="$ENV_DIR/bin/mojo"
export MODULAR_HOME="$ENV_DIR/share/max"
export PATH="$HOME/.pixi/bin:$PATH"

if [[ ! -x "$MOJO" ]]; then
    echo "[tc-probe] mojo not found at $MOJO — run benchmarks/llm_smoke/nvidia_race/setup_vm.sh first" >&2
    exit 1
fi
if [[ ! -x "$CUDA_HOME/bin/nvcc" ]]; then
    echo "[tc-probe] nvcc not found at $CUDA_HOME/bin/nvcc — set CUDA_HOME" >&2
    exit 1
fi

# sm target: explicit SM_TARGET wins; otherwise map the GPU name.
SM_TARGET="${SM_TARGET:-}"
if [[ -z "$SM_TARGET" ]]; then
    GPU_NAME="$(nvidia-smi --query-gpu=name --format=csv,noheader -i 0 | head -1)"
    case "$GPU_NAME" in
        *H100*) SM_TARGET="sm_90" ;;
        *A100*) SM_TARGET="sm_80" ;;
        *L4*) SM_TARGET="sm_89" ;;
        *)
            echo "[tc-probe] cannot map GPU '$GPU_NAME' to an sm target; set SM_TARGET" >&2
            exit 1
            ;;
    esac
    echo "[tc-probe] detected '$GPU_NAME' -> $SM_TARGET"
fi

mkdir -p "$OUT_DIR"

echo "[tc-probe] $($CUDA_HOME/bin/nvcc --version | tail -1)"

# ── angle 1: the runtime-loaded kernels. Compiled to PTX at compute_80 (mma.sync.m16n8k16
#    needs Ampere+; the driver JITs this PTX to the live GPU's SASS at cuModuleLoadData —
#    one binary PTX payload serves BOTH sm_80 and sm_90 fleets), then embedded as a C array.
echo "[tc-probe] compiling tc_rt_kernels.cu -> PTX (compute_80, driver-JIT'd at load)"
"$CUDA_HOME/bin/nvcc" -ptx -arch=compute_80 \
    "$REPO_ROOT/benchmarks/llm_smoke/nvidia_race/tc_rt_kernels.cu" \
    -o "$OUT_DIR/tc_rt_kernels.ptx"
python3 - "$OUT_DIR/tc_rt_kernels.ptx" "$OUT_DIR/tc_rt_ptx.h" <<'PY'
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
chunks = []
for i in range(0, len(data), 24):
    chunks.append(",".join(str(b) for b in data[i : i + 24]))
with open(dst, "w") as out:
    out.write("/* generated by build_tc_probe.sh from tc_rt_kernels.ptx — embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
print(f"[tc-probe] embedded {len(data)} bytes of PTX into {dst}")
PY

echo "[tc-probe] compiling tc_shim.cu for $SM_TARGET"
"$CUDA_HOME/bin/nvcc" -O3 -arch="$SM_TARGET" -Xcompiler -fPIC -I"$OUT_DIR" \
    -c "$REPO_ROOT/benchmarks/llm_smoke/nvidia_race/tc_shim.cu" \
    -o "$OUT_DIR/tc_shim.o"

SHIM_SRC="$REPO_ROOT/benchmarks/llm_smoke/nvidia_race/tc_escape_probe.mojo"

echo "[tc-probe] link recipe 1: plain mojo build -Xlinker"
if "$MOJO" build -D ALGENTA_GPU -D ALGENTA_CUDA --target-accelerator "$SM_TARGET" \
    -I "$REPO_ROOT/mojo/engine" "$SHIM_SRC" \
    -o "$OUT_DIR/tc_escape_probe" \
    -Xlinker "$OUT_DIR/tc_shim.o" \
    -Xlinker -lcublas -Xlinker -lcudart \
    -Xlinker "-L$CUDA_HOME/lib64" 2>"$OUT_DIR/mojo_build_plain.log"; then
    echo "[tc-probe] LINKED via plain mojo build -Xlinker (recipe 1)"
else
    echo "[tc-probe] recipe 1 refused:"
    grep -m2 -E "error|undefined" "$OUT_DIR/mojo_build_plain.log" >&2 || tail -3 "$OUT_DIR/mojo_build_plain.log" >&2
    echo "[tc-probe] link recipe 2: --emit object + clang with MAX runtime + CUDA libs"
    "$MOJO" build -D ALGENTA_GPU -D ALGENTA_CUDA --target-accelerator "$SM_TARGET" \
        -I "$REPO_ROOT/mojo/engine" "$SHIM_SRC" \
        --emit object -o "$OUT_DIR/tc_escape_probe.o"
    MAX_LIB="$(dirname "$(find "$ENV_DIR" -name 'libMGPRT.so' | head -1)")"
    PYLIB="$(find "$ENV_DIR/lib" -maxdepth 1 -name 'libpython3*.so' | sort | head -1)"
    CLANG_BIN="$(command -v clang || echo /usr/bin/clang)"
    RUNTIME_LIBS=(-lKGENCompilerRTShared -lAsyncRTRuntimeGlobals -lMSupportGlobals -lMGPRT)
    if ls "$MAX_LIB"/libAsyncRTMojoBindings.* >/dev/null 2>&1; then
        RUNTIME_LIBS+=(-lAsyncRTMojoBindings)
    fi
    if [[ ! -e "$MAX_LIB/libstdc++.so" ]]; then
        stdcxx_versioned="$(find "$MAX_LIB" -maxdepth 1 -name 'libstdc++.so.*' | sort -V | tail -n 1)"
        if [[ -n "$stdcxx_versioned" ]]; then
            ln -sf "$(basename "$stdcxx_versioned")" "$MAX_LIB/libstdc++.so"
        fi
    fi
    "$CLANG_BIN" "$OUT_DIR/tc_escape_probe.o" "$OUT_DIR/tc_shim.o" \
        -o "$OUT_DIR/tc_escape_probe" \
        -L"$MAX_LIB" -Wl,-rpath,"$MAX_LIB" \
        -L"$CUDA_HOME/lib64" -Wl,-rpath,"$CUDA_HOME/lib64" \
        "${RUNTIME_LIBS[@]}" -lcublas -lcudart "$PYLIB" \
        -lstdc++ -ldl -lpthread -lm
    echo "[tc-probe] LINKED via object + clang recipe (recipe 2)"
fi

chmod +x "$OUT_DIR/tc_escape_probe"
echo "[tc-probe] binary ready: $OUT_DIR/tc_escape_probe"
