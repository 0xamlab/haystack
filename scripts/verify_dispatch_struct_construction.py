#!/usr/bin/env python3
"""Compile-check the struct construction the dispatch generator emits.

Why this exists
---------------
`scripts/generate_runtime_library_dispatch.py` emits a decoder per struct that
appears in a runtime-library signature. For a struct declaring only
``fn __init__(out self)`` it must default-construct and then assign each field;
emitting positional construction ``T(f0, ..., fN)`` does not compile. That defect
shipped once: `make build-mojo` failed, so the generated artifacts were never
refreshed, so 23 compiled-and-tested kernels were unreachable from the SDK.

Nothing gated it, because the only proof was a full ~495-module build that needs
about 18 GB of RSS and many minutes. This script is the bounded equivalent: it
synthesises one small Mojo program exercising the exact emitted construction
shape for every ``assign`` struct that has a parser in the generated table, then
compiles it. Seconds, under 4 GB, and it fails on precisely the defect class.

Usage:
    python3 scripts/verify_dispatch_struct_construction.py
    python3 scripts/verify_dispatch_struct_construction.py --print-only
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from apps.runtime.mojo_inventory import discover_runtime_library_modules  # noqa: E402

ENGINE_DIR = ROOT / "mojo" / "engine"
DISPATCH = ENGINE_DIR / "runtime_library_dispatch_generated.mojo"
MOJO_ENV = ROOT / "mojo_env"
MOJO_BIN = MOJO_ENV / ".pixi" / "envs" / "default" / "bin" / "mojo"

# Field types the probe can synthesise a value for. Anything else is skipped for
# that field (the struct is still default-constructed, which is the part that
# used to fail to compile).
_SCALAR_LITERALS = {
    "Int": "1",
    "Float64": "1.0",
    "Float32": "Float32(1.0)",
    "Bool": "True",
    "String": '"x"',
    "UInt8": "UInt8(1)",
    "UInt16": "UInt16(1)",
    "UInt32": "UInt32(1)",
    "UInt64": "UInt64(1)",
}
_LIST_ELEMENTS = {"Float64": "1.0", "Int": "1", "Float32": "Float32(1.0)", "String": '"x"'}


def _load_generator():
    generator_path = ROOT / "scripts" / "generate_runtime_library_dispatch.py"
    spec = importlib.util.spec_from_file_location("_dispatch_generator", generator_path)
    if spec is None or spec.loader is None:  # pragma: no cover
        raise SystemExit("cannot load the dispatch generator")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _assign_structs_with_parsers() -> list[tuple[str, str, list[tuple[str, str]]]]:
    """[(module_import_path, struct_name, fields)] for emitted `assign` structs."""
    generator = _load_generator()
    dispatch_source = DISPATCH.read_text(encoding="utf-8") if DISPATCH.is_file() else ""
    found: list[tuple[str, str, list[tuple[str, str]]]] = []
    for module in discover_runtime_library_modules(executable_only=True):
        for name, (fields, construction) in generator._parse_struct_defs(module.path).items():
            if construction != "assign":
                continue
            if not re.search(rf"raises -> {re.escape(name)}:", dispatch_source):
                continue
            found.append((module.import_path, name, fields))
    found.sort()
    return found


def _render_probe(targets: list[tuple[str, str, list[tuple[str, str]]]]) -> str:
    lines = [
        '"""Generated by scripts/verify_dispatch_struct_construction.py — do not commit."""',
    ]
    for module, name, _fields in targets:
        lines.append(f"from {module} import {name}")
    lines += ["", "fn main() raises:"]
    for index, (_module, name, fields) in enumerate(targets):
        var = f"v{index}"
        lines.append(f"    var {var} = {name}()")
        for field_name, field_type in fields:
            if field_type in _SCALAR_LITERALS:
                lines.append(f"    {var}.{field_name} = {_SCALAR_LITERALS[field_type]}")
            elif field_type.startswith("List[") and field_type.endswith("]"):
                inner = field_type[5:-1]
                if inner not in _LIST_ELEMENTS:
                    continue
                tmp = f"{var}_{field_name}"
                lines.append(f"    var {tmp} = List[{inner}]()")
                lines.append(f"    {tmp}.append({_LIST_ELEMENTS[inner]})")
                lines.append(f"    {var}.{field_name} = {tmp}^")
        lines.append(f'    print("ok {name}")')
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--print-only", action="store_true", help="emit the probe and exit")
    args = parser.parse_args()

    targets = _assign_structs_with_parsers()
    if not targets:
        print("no assign-strategy structs have an emitted parser — nothing to verify")
        return 0

    probe = _render_probe(targets)
    if args.print_only:
        print(probe)
        return 0

    names = ", ".join(f"{module}.{name}" for module, name, _ in targets)
    print(f"verifying default-construct + field assignment for: {names}")

    if not MOJO_BIN.exists():
        print(f"SKIP: no Mojo toolchain at {MOJO_BIN} (run `make setup-mojo`)")
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        probe_path = Path(tmp) / "verify_struct_construction.mojo"
        probe_path.write_text(probe, encoding="utf-8")
        env = {
            **os.environ,
            "MODULAR_HOME": str(MOJO_ENV / ".pixi" / "envs" / "default" / "share" / "max"),
            "MODULAR_CACHE_DIR": str(ROOT / ".cache" / "modular"),
            "XDG_DATA_HOME": str(ROOT / ".local" / "share"),
            "MODULAR_TELEMETRY_ENABLED": "0",
        }
        result = subprocess.run(  # noqa: S603
            [str(MOJO_BIN), "run", f"-I{ENGINE_DIR}", str(probe_path)],
            cwd=str(MOJO_ENV),
            env=env,
            capture_output=True,
            text=True,
            timeout=600,
            check=False,
        )

    errors = [line for line in result.stderr.splitlines() if ": error:" in line]
    if result.returncode != 0 or errors:
        print("FAIL: the emitted struct construction does not compile.")
        print("      Regenerate with `make inventory-refresh` after fixing")
        print("      scripts/generate_runtime_library_dispatch.py.")
        for line in errors[:20]:
            print(f"  {line}")
        if not errors:
            print(result.stderr[-2000:])
        return 1

    print(f"✅ {len(targets)} assign-strategy struct(s) construct and assign cleanly")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
