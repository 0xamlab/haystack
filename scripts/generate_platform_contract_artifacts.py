from __future__ import annotations

import json
import sys
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from apps.platform_contract import (  # noqa: E402
    load_platform_contract,
    load_platform_contract_manifest,
)

_GENERATED_NOTE = "Generated by scripts/generate_platform_contract_artifacts.py."


def _write(path: Path, content: str) -> None:
    path.write_text(content.rstrip() + "\n")


def _python_dict(value: object) -> str:
    return pformat(value, width=88, sort_dicts=False)


def main() -> None:
    contract = load_platform_contract()
    manifest = load_platform_contract_manifest()
    defaults = manifest["defaults"]
    privacy_registry = manifest["privacy_registry"]
    read_only_default = bool(defaults["read_only_default"])
    write_confirmation_required = bool(defaults["write_confirmation_required"])
    primary_data_query_contract_ts = json.dumps(
        contract.primary_data_query_contract,
        indent=2,
    )
    capability_plane_contract_ts = json.dumps(
        contract.capability_plane,
        indent=2,
    )

    _write(
        ROOT / "apps" / "platform_contract_constants.py",
        f'''"""{_GENERATED_NOTE}"""

CONTRACT_VERSION = {contract.contract_version!r}
BRAND = {contract.brand!r}
API_BASE_URL = {contract.api_base_url!r}
MCP_ENDPOINT = {contract.mcp_endpoint!r}
MCP_TOOLS_ENDPOINT = {contract.mcp_tools_endpoint!r}
AUTH_SCHEME = {contract.auth_scheme!r}
API_KEY_PREFIX_LIVE = {contract.api_key_prefix_live!r}
API_KEY_PREFIX_TEST = {contract.api_key_prefix_test!r}
LEGACY_HEADERS = {tuple(contract.legacy_headers)!r}
LEGACY_ENV_VARS = {tuple(contract.legacy_env_vars)!r}
LEGACY_DOMAINS = {tuple(contract.legacy_domains)!r}
ALGENTA_OWNED_HOSTS = {tuple(contract.algenta_owned_hosts)!r}
ALGENTA_OWNED_SUFFIXES = {tuple(contract.algenta_owned_suffixes)!r}
VENDOR_TELEMETRY_HOSTS = {tuple(contract.vendor_telemetry_hosts)!r}
PRIVATE_HOST_SUFFIXES = {tuple(contract.private_host_suffixes)!r}
DEPRECATION_WINDOW_DAYS = {contract.deprecation_window_days}
PLAN_LIMITS = {_python_dict(contract.plan_limits)}
PRIMARY_DATA_QUERY_CONTRACT = {_python_dict(contract.primary_data_query_contract)}
CAPABILITY_PLANE_CONTRACT = {_python_dict(contract.capability_plane)}
''',
    )

    for rel_path in (
        ("packages", "python-sdk", "decision_engine", "_contract.py"),
        ("packages", "algenta", "algenta", "_contract.py"),
    ):
        _write(
            ROOT.joinpath(*rel_path),
            f'''"""{_GENERATED_NOTE}"""

CONTRACT_VERSION = {contract.contract_version!r}
BRAND = {contract.brand!r}
DEFAULT_BASE_URL = {contract.api_base_url!r}
MCP_ENDPOINT = {contract.mcp_endpoint!r}
MCP_TOOLS_ENDPOINT = {contract.mcp_tools_endpoint!r}
AUTH_SCHEME = {contract.auth_scheme!r}
API_KEY_PREFIX_LIVE = {contract.api_key_prefix_live!r}
API_KEY_PREFIX_TEST = {contract.api_key_prefix_test!r}
LEGACY_HEADERS = {tuple(contract.legacy_headers)!r}
LEGACY_ENV_VARS = {tuple(contract.legacy_env_vars)!r}
LEGACY_DOMAINS = {tuple(contract.legacy_domains)!r}
ALGENTA_OWNED_HOSTS = {tuple(contract.algenta_owned_hosts)!r}
ALGENTA_OWNED_SUFFIXES = {tuple(contract.algenta_owned_suffixes)!r}
VENDOR_TELEMETRY_HOSTS = {tuple(contract.vendor_telemetry_hosts)!r}
PRIVATE_HOST_SUFFIXES = {tuple(contract.private_host_suffixes)!r}
DEPRECATION_WINDOW_DAYS = {contract.deprecation_window_days}
READ_ONLY_DEFAULT = {read_only_default}
WRITE_CONFIRMATION_REQUIRED = {write_confirmation_required}
PLAN_LIMITS = {_python_dict(contract.plan_limits)}
INTEGRATIONS = {_python_dict(list(contract.integrations))}
PRIMARY_DATA_QUERY_CONTRACT = {_python_dict(contract.primary_data_query_contract)}
CAPABILITY_PLANE_CONTRACT = {_python_dict(contract.capability_plane)}
''',
        )

    _write(
        ROOT / "packages" / "ts-sdk" / "src" / "contract.ts",
        f"""// {_GENERATED_NOTE}

export const CONTRACT_VERSION = {json.dumps(contract.contract_version)};
export const BRAND = {json.dumps(contract.brand)};
export const DEFAULT_BASE_URL = {json.dumps(contract.api_base_url)};
export const MCP_ENDPOINT = {json.dumps(contract.mcp_endpoint)};
export const MCP_TOOLS_ENDPOINT = {json.dumps(contract.mcp_tools_endpoint)};
export const AUTH_SCHEME = {json.dumps(contract.auth_scheme)};
export const API_KEY_PREFIX_LIVE = {json.dumps(contract.api_key_prefix_live)};
export const API_KEY_PREFIX_TEST = {json.dumps(contract.api_key_prefix_test)};
export const LEGACY_HEADERS = {json.dumps(list(contract.legacy_headers))} as const;
export const LEGACY_ENV_VARS = {json.dumps(list(contract.legacy_env_vars))} as const;
export const LEGACY_DOMAINS = {json.dumps(list(contract.legacy_domains))} as const;
export const ALGENTA_OWNED_HOSTS = {json.dumps(list(contract.algenta_owned_hosts))} as const;
export const ALGENTA_OWNED_SUFFIXES = {json.dumps(list(contract.algenta_owned_suffixes))} as const;
export const VENDOR_TELEMETRY_HOSTS = {json.dumps(list(contract.vendor_telemetry_hosts))} as const;
export const PRIVATE_HOST_SUFFIXES = {json.dumps(list(contract.private_host_suffixes))} as const;
export const DEPRECATION_WINDOW_DAYS = {contract.deprecation_window_days};
export const READ_ONLY_DEFAULT = {json.dumps(read_only_default)};
export const WRITE_CONFIRMATION_REQUIRED = {json.dumps(write_confirmation_required)};
export const PLAN_LIMITS = {json.dumps(contract.plan_limits, indent=2)};
export const INTEGRATIONS = {json.dumps(list(contract.integrations), indent=2)};
export const PRIMARY_DATA_QUERY_CONTRACT = {primary_data_query_contract_ts};
export const CAPABILITY_PLANE_CONTRACT = {capability_plane_contract_ts};
""",
    )

    gateway_registry_ts = f"""// {_GENERATED_NOTE}

export const ALGENTA_OWNED_HOSTS = {json.dumps(list(privacy_registry["algenta_owned_hosts"]))} as const;
export const ALGENTA_OWNED_SUFFIXES = {json.dumps(list(privacy_registry["algenta_owned_suffixes"]))} as const;
export const PRIVATE_HOST_SUFFIXES = {json.dumps(list(privacy_registry["private_host_suffixes"]))} as const;
"""
    _write(ROOT / "apps" / "gateway" / "src" / "privacy_registry.ts", gateway_registry_ts)



if __name__ == "__main__":
    main()
