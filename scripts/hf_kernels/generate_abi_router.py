#!/usr/bin/env python3
"""Emit the family-scoped request router (Mojo) for one HF kernel family.

Only the request types a family DECLARES are compiled in (plan v3, "Router (family-scoped)"):
a stats family gets `library_execute` alone and never pulls dataset/stream/session state or GPU
dependencies into its build; the LLM family declares the resident-session routes. Mirrors the
routing in mojo/engine/main.mojo verbatim (same functions, same state objects), so the in-process
path and the worker agree; no frozen file is modified.

Usage: generate_abi_router.py --request-types library_execute qwen3_decode_open ... --output <stage>/hf_abi_router_generated.mojo
"""
from __future__ import annotations

import argparse
from pathlib import Path

DATASET_ROUTES = {"dataset_open", "dataset_close", "dataset_list", "batch_execute", "pipeline_execute", "query_execute", "stream_open", "stream_next", "stream_close"}
STREAM_ROUTES = {"stream_open", "stream_next", "stream_close"}
QWEN3_ROUTES = {"qwen3_decode_open", "qwen3_decode_next", "qwen3_decode_close"}
KNOWN = {"library_execute"} | DATASET_ROUTES | QWEN3_ROUTES

ROUTE_BODY = {
    "library_execute": "return dispatch_runtime_library(raw)",
    "batch_execute": "return run_batch_execute(dispatch_runtime_library, raw, state.datasets)",
    "pipeline_execute": "return run_pipeline_execute(dispatch_runtime_library, raw, state.datasets)",
    "query_execute": "return run_query(raw, state.datasets)",
    "dataset_open": "return state.datasets.open_from_json(raw)",
    "dataset_close": "return state.datasets.close_from_json(raw)",
    "dataset_list": "return state.datasets.list_json()",
    "stream_open": "return state.streams.open_from_json(raw, state.datasets)",
    "stream_next": "return state.streams.next_from_json(raw, state.datasets)",
    "stream_close": "return state.streams.close_from_json(raw)",
    "qwen3_decode_open": "return state.qwen3.open_from_json(raw)",
    "qwen3_decode_next": "return state.qwen3.next_from_json(raw)",
    "qwen3_decode_close": "return state.qwen3.close_from_json(raw)",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--request-types", nargs="+", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--backend", default="cpu", choices=["cpu", "metal", "cuda"], help="cuda: the qwen3 decode routes bind hfkernel's CUDA session registry (same wire format)")
    a = ap.parse_args()
    types = list(dict.fromkeys(a.request_types))
    unknown = [t for t in types if t not in KNOWN]
    if unknown:
        raise SystemExit(f"unknown request types (not in main.mojo's router): {unknown}")
    need_datasets = bool(DATASET_ROUTES & set(types))
    need_streams = bool(STREAM_ROUTES & set(types))
    need_qwen3 = bool(QWEN3_ROUTES & set(types))
    lines = ['"""AUTO-GENERATED by scripts/hf_kernels/generate_abi_router.py — do not edit."""',
             "from runtime_library_dispatch_generated import dispatch_runtime_library"]
    if need_datasets:
        lines.append("from algenta_runtime.session import ResidentDatasets")
    if {"batch_execute"} & set(types):
        lines.append("from algenta_runtime.batch import run_batch_execute")
    if {"pipeline_execute"} & set(types):
        lines.append("from algenta_runtime.pipeline import run_pipeline_execute")
    if {"query_execute"} & set(types):
        lines.append("from algenta_runtime.query import run_query")
    if need_streams:
        lines.append("from algenta_runtime.stream import ResidentStreams")
    if need_qwen3:
        if a.backend == "cuda":
            lines.append("from cuda_decode_session import CudaDecodeSessions as Qwen3DecodeSessions")
        else:
            lines.append("from algenta_runtime.qwen3_decode_session import Qwen3DecodeSessions")
    lines += ["", "", "struct RouterState(Movable):", '    """Per-handle resident state; only what this family\'s declared routes need."""', "    var declared: List[String]"]
    if need_datasets:
        lines.append("    var datasets: ResidentDatasets")
    if need_streams:
        lines.append("    var streams: ResidentStreams")
    if need_qwen3:
        lines.append("    var qwen3: Qwen3DecodeSessions")
    lines += ["", "    def __init__(out self):", "        self.declared = List[String]()"]
    for t in types:
        lines.append(f'        self.declared.append(String("{t}"))')
    if need_datasets:
        lines.append("        self.datasets = ResidentDatasets()")
    if need_streams:
        lines.append("        self.streams = ResidentStreams()")
    if need_qwen3:
        lines.append("        self.qwen3 = Qwen3DecodeSessions()")
    lines += ["", "    def is_declared(self, msg_type: String) -> Bool:", "        for t in self.declared:", "            if t == msg_type:", "                return True", "        return False", "", "",
              "def route(msg_type: String, raw: String, mut state: RouterState) raises -> String:",
              '    """Dispatch a declared request type exactly as mojo/engine/main.mojo does."""']
    first = True
    for t in types:
        lines.append(f'    {"if" if first else "elif"} msg_type == "{t}":')
        lines.append(f"        {ROUTE_BODY[t]}")
        first = False
    lines.append('    raise Error("route_undeclared: " + msg_type)')
    Path(a.output).write_text("\n".join(lines) + "\n")
    print(f"router: {len(types)} route(s) {types} -> {a.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
