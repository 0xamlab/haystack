#!/usr/bin/env python3
"""Emit the count-relation guard Mojo module for one HF kernel family.

The runtime-library contract publishes, per function, which Int parameters count elements of
which list parameters (`count_relations`). Reading past a list inside the runtime is an
uncatchable process abort, so the check must run at the native boundary (ABI.md 3.3) before the
frozen dispatch sees the request — not only in the Python wrapper. This generator ports
`packages/algenta/algenta/runtime_count_guard.py` (codes, roles, division-based `count_fits`,
unmeasurable-argument refusal) to Mojo for the family's modules. Regenerate on every build.

Usage: generate_abi_guard.py --contract packages/algenta/algenta/runtime_library_contract.json \
           --modules stats ab_testing --output <stage>/hf_abi_guard_generated.mojo
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

PRELUDE = '''"""AUTO-GENERATED by scripts/hf_kernels/generate_abi_guard.py — do not edit."""
from json.parser import json_get_array, json_array_len, json_array_get
from conv import parse_int

comptime COUNT_CODE = "count_exceeds_list_length"
comptime UNMEASURABLE_CODE = "invalid_arguments"


def _esc(s: String) -> String:
    var out = String()
    for i in range(s.byte_length()):
        var b = s.unsafe_ptr()[i]
        if b == 34 or b == 92:
            out += "\\\\"
        if b >= 32:
            out += chr(Int(b))
    return out


def _envelope(code: String, message: String) -> String:
    var m = _esc(message)
    return '{"error":"' + code + ': ' + m + '","error_code":"' + code + '","error_message":"' + m + '"}'


def _is_int_literal(tok: String) -> Bool:
    var n = tok.byte_length()
    if n == 0:
        return False
    var p = tok.unsafe_ptr()
    var i = 0
    if p[0] == 45:  # '-'
        i = 1
    if i >= n:
        return False
    while i < n:
        var b = p[i]
        if b < 48 or b > 57:
            return False
        i += 1
    return True


def _measure(tok: String) -> Int:
    """Elements the runtime will see in an argument token, or -1 if unmeasurable here."""
    var n = tok.byte_length()
    if n == 0:
        return -1
    var p = tok.unsafe_ptr()
    if p[0] == 91:  # '['
        return json_array_len(tok)
    # "@u8:<base64>" packed Float64 buffer: sextets*6//8 elements, non-alphabet chars skipped.
    if n >= 6 and p[0] == 34 and p[1] == 64 and p[2] == 117 and p[3] == 56 and p[4] == 58:
        var sextets = 0
        var i = 5
        while i < n - 1:
            var b = p[i]
            if (b >= 65 and b <= 90) or (b >= 97 and b <= 122) or (b >= 48 and b <= 57) or b == 43 or b == 47:
                sextets += 1
            i += 1
        return (sextets * 6) // 8
    return -1


def _count_fits(factors: List[Int], available: Int, index_role: Bool) -> Bool:
    """Division-based product check (never multiplies: Int wraps inside the runtime)."""
    if available < 0:
        return False
    if index_role:
        for f in factors:
            if f < 0:
                return False
    for f in factors:
        if f == 0:
            return True
    var remaining = available
    for f in factors:
        if f < 0:
            return True
        if f > remaining:
            return False
        remaining //= f
    return True


def _join_names(names: List[String], sep: String) -> String:
    var out = String()
    for i in range(len(names)):
        if i > 0:
            out += sep
        out += names[i]
    return out


def _join_ints(values: List[Int], sep: String) -> String:
    var out = String()
    for i in range(len(values)):
        if i > 0:
            out += sep
        out += String(values[i])
    return out


def _check_relation(
    module: String, function: String, list_name: String, listed: String,
    factor_names: List[String], factors: List[Int], plus: Int, index_role: Bool, element_scope: Bool,
) -> String:
    var counted = String()
    for i in range(len(factor_names)):
        if i > 0:
            counted += ", "
        counted += factor_names[i] + "=" + String(factors[i])
    var requirement = _join_names(factor_names, " * ") + " = " + _join_ints(factors, " * ")
    if plus > 0:
        requirement = _join_names(factor_names, " * ") + " + " + String(plus) + " = " + _join_ints(factors, " * ") + " + " + String(plus)
    var n_items = 1
    if element_scope:
        if listed.byte_length() == 0 or listed.unsafe_ptr()[0] != 91:
            return _envelope(UNMEASURABLE_CODE, module + "." + function + ": '" + list_name + "' is bounded by a declared element count per element, and it is not a list; the call is declined rather than sent unchecked.")
        n_items = json_array_len(listed)
    for k in range(n_items):
        var target = list_name
        var item = listed
        if element_scope:
            item = json_array_get(listed, k)
            target = list_name + "[" + String(k) + "]"
        var length = _measure(item)
        if length < 0:
            return _envelope(UNMEASURABLE_CODE, module + "." + function + ": '" + target + "' is bounded by a declared element count, and its length cannot be determined before the call. Reading past the end of that list inside the runtime is an uncatchable abort of the whole process, so the call is declined rather than sent unchecked. Pass '" + list_name + "' as a list or as a \\"@u8:<base64>\\" buffer.")
        if _count_fits(factors, length - plus, index_role):
            continue
        var negative = False
        for f in factors:
            if f < 0:
                negative = True
        if index_role and negative:
            return _envelope(COUNT_CODE, module + "." + function + ": " + counted + " is a negative index into '" + target + "'. The runtime does not read a negative index from the end of the list; it aborts the whole worker process. An index must be 0 or greater.")
        if index_role:
            return _envelope(COUNT_CODE, module + "." + function + ": " + counted + " indexes past the end of '" + target + "', which has " + String(length) + " element(s); reading it would abort the runtime worker. '" + list_name + "' must hold at least " + requirement + " element(s).")
        return _envelope(COUNT_CODE, module + "." + function + ": " + counted + " counts more elements than '" + target + "' holds (" + String(length) + "); reading them would abort the runtime worker. '" + list_name + "' must hold at least " + requirement + " element(s).")
    return String("")

'''


def emit_function(module: str, fn: dict) -> tuple[str, str]:
    params = [p["name"] for p in fn["params"]]
    idx = {name: i for i, name in enumerate(params)}
    ident = f"_cr_{module.replace('.', '_')}__{fn['name']}"
    lines = [f"def {ident}(raw: String) -> String:", '    var args = json_get_array(raw, "args")', "    var n_args = json_array_len(args)"]
    for r_i, rel in enumerate(fn["count_relations"]):
        factor_idx = [idx[n] for n in rel["factors"]]
        needed = ", ".join(str(i) for i in factor_idx)
        lines.append(f"    # relation {r_i}: bounds {rel['bounds']} factors {rel['factors']} plus {rel['plus']} role {rel['role']} scope {rel['scope']}")
        cond = " and ".join(f"{i} < n_args" for i in factor_idx)
        lines.append(f"    if {cond}:")
        lines.append("        var factors = List[Int]()")
        lines.append("        var factor_names = List[String]()")
        lines.append("        var measurable = True")
        for name, i in zip(rel["factors"], factor_idx):
            lines.append(f"        var t{i} = json_array_get(args, {i})")
            lines.append(f"        if _is_int_literal(t{i}):")
            lines.append(f"            factors.append(parse_int(t{i}))")
            lines.append(f'            factor_names.append(String("{name}"))')
            lines.append("        else:")
            lines.append("            measurable = False")
        lines.append("        if measurable:")
        index_role = "True" if (rel["role"] == "index" or rel["plus"] > 0) else "False"
        element_scope = "True" if rel["scope"] == "element_length" else "False"
        for bound in rel["bounds"]:
            b = idx[bound]
            lines.append(f"            if {b} < n_args:")
            lines.append(f'                var r = _check_relation("{module}", "{fn["name"]}", "{bound}", json_array_get(args, {b}), factor_names, factors, {rel["plus"]}, {index_role}, {element_scope})')
            lines.append("                if r.byte_length() > 0:")
            lines.append("                    return r")
    lines.append('    return String("")')
    return "\n".join(lines) + "\n\n\n", ident


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--contract", default="packages/algenta/algenta/runtime_library_contract.json")
    ap.add_argument("--modules", nargs="+", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--stub", action="store_true", help="TEST ONLY: emit a guard that never refuses (to demonstrate the abort class)")
    ap.add_argument("--exclude", nargs="*", default=[], help="functions refused in-process, as module.function or module.* (e.g. datetime.now_epoch env.*)")
    a = ap.parse_args()
    contract = json.loads(Path(a.contract).read_text())
    wanted = set(a.modules)
    parts = [PRELUDE]
    dispatch = ["def check_count_relations(module: String, function: String, raw: String) -> String:"]
    n_fn = 0
    for m in contract["modules"]:
        if m["name"] not in wanted:
            continue
        for fn in m["functions"]:
            if not fn.get("count_relations") or a.stub:
                continue
            body, ident = emit_function(m["name"], fn)
            parts.append(body)
            dispatch.append(f'    if module == "{m["name"]}" and function == "{fn["name"]}":')
            dispatch.append(f"        return {ident}(raw)")
            n_fn += 1
    dispatch.append('    return String("")')
    parts.append("\n".join(dispatch) + "\n\n\n")
    # Functions whose implementation needs the Python interop bridge crash in-process (Stage 2,
    # RQ-G: SIGSEGV with no libpython loaded). They are refused at the boundary, not shipped.
    excl = ["def is_function_excluded(module: String, function: String) -> Bool:"]
    for item in a.exclude:
        mod, _, fn = item.rpartition(".")
        if fn == "*":
            excl.append(f'    if module == "{mod}":\n        return True')
        else:
            excl.append(f'    if module == "{mod}" and function == "{fn}":\n        return True')
    excl.append("    return False")
    parts.append("\n".join(excl) + "\n")
    Path(a.output).write_text("".join(parts))
    print(f"guard: {n_fn} guarded function(s), {len(a.exclude)} exclusion rule(s) for modules {sorted(wanted)} -> {a.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
