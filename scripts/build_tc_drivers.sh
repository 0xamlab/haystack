#!/usr/bin/env bash
# build_tc_drivers.sh — build the CUDA race-driver battery for the TC integration round
# (feat/tc-int) ON A GPU VM: for every raced driver it builds TWO arms —
#
#   native   — the exact campaign flags, NO TC (the A/B control; link line byte-unmodified)
#   tc       — the same flags PLUS -D ALGENTA_TC_SHIM and the nvcc tc_shim.o linked in
#              (-Xlinker tc_shim.o -Xlinker -lcublas -Xlinker -lcudart, the probe-proven
#              recipe; object+clang fallback mirrors setup_vm.sh's build_one_driver)
#
# Drivers (arm suffix: _tc on the TC binaries, plain names for the native controls):
#   qwen3_generate_cuda        fixture prefill + 16/16 oracle (f32 session, B1 levers)
#   qwen3_p3_session_cuda      the packed3 session gate battery G0/G1/G2 (p3 TC prefill)
#   qwen3_serve_batched_cuda   serve cells + --selftest (admission-prefill TC), s2l7 flags
#   qwen25_7b_p3_graph_cuda    7B lane (ALGENTA_STAGE_18944; p3 TC prefill, graph decode)
#
# Usage (on algenta-ent-a100 / algenta-ent-h100, repo root = this tree):
#   bash scripts/build_tc_drivers.sh                 # auto-detects sm from nvidia-smi
#   SM_TARGET=sm_80 OUT_DIR=~/tc_bins bash scripts/build_tc_drivers.sh
#   ARMS=tc bash scripts/build_tc_drivers.sh         # only the TC arm (or ARMS=native)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="${OUT_DIR:-$HOME/algenta_nv}"
CUDA_HOME="${CUDA_HOME:-/usr/local/cuda}"
ARMS="${ARMS:-native tc}"
ENV_DIR="$REPO_ROOT/mojo_env/.pixi/envs/default"
MOJO="$ENV_DIR/bin/mojo"
export MODULAR_HOME="$ENV_DIR/share/max"
export PATH="$HOME/.pixi/bin:$PATH"

[[ -x "$MOJO" ]] || { echo "[tc-drivers] mojo missing at $MOJO — run setup_vm.sh first" >&2; exit 1; }
[[ -x "$CUDA_HOME/bin/nvcc" ]] || { echo "[tc-drivers] nvcc missing — set CUDA_HOME" >&2; exit 1; }

SM_TARGET="${SM_TARGET:-}"
if [[ -z "$SM_TARGET" ]]; then
    GPU_NAME="$(nvidia-smi --query-gpu=name --format=csv,noheader -i 0 | head -1)"
    case "$GPU_NAME" in
        *H100*) SM_TARGET="sm_90" ;;
        *A100*) SM_TARGET="sm_80" ;;
        *L4*) SM_TARGET="sm_89" ;;
        *) echo "[tc-drivers] cannot map GPU '$GPU_NAME'; set SM_TARGET" >&2; exit 1 ;;
    esac
    echo "[tc-drivers] detected '$GPU_NAME' -> $SM_TARGET"
fi

mkdir -p "$OUT_DIR"

TC_SHIM_OBJ="/tmp/tc_shim_${SM_TARGET}.o"
TC_SHIM_DIR="/tmp/tc_shim_build_${SM_TARGET}"
tc_shim_object() {
    # The shim's ANGLE-1 section #includes the EMBEDDED-PTX header build_tc_probe.sh's
    # recipe generates — reproduce it here (compute_80 PTX, driver-JIT'd per GPU; one
    # payload serves both fleets), then compile the shim with the header on the include path.
    if [[ ! -f "$TC_SHIM_OBJ" ]]; then
        mkdir -p "$TC_SHIM_DIR"
        if [[ ! -f "$TC_SHIM_DIR/tc_rt_ptx.h" ]]; then
            echo "[tc-drivers] nvcc tc_rt_kernels.cu -> embedded PTX header"
            "$CUDA_HOME/bin/nvcc" -ptx -arch=compute_80 \
                "$REPO_ROOT/benchmarks/llm_smoke/nvidia_race/tc_rt_kernels.cu" \
                -o "$TC_SHIM_DIR/tc_rt_kernels.ptx"
            python3 - "$TC_SHIM_DIR/tc_rt_kernels.ptx" "$TC_SHIM_DIR/tc_rt_ptx.h" <<'PY'
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
chunks = []
for i in range(0, len(data), 24):
    chunks.append(",".join(str(b) for b in data[i : i + 24]))
with open(dst, "w") as out:
    out.write("/* generated by build_tc_drivers.sh — embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
PY
        fi
        echo "[tc-drivers] nvcc tc_shim.cu -> $TC_SHIM_OBJ"
        "$CUDA_HOME/bin/nvcc" -O3 -arch="$SM_TARGET" -Xcompiler -fPIC \
            -I "$TC_SHIM_DIR" \
            -c "$REPO_ROOT/benchmarks/llm_smoke/nvidia_race/tc_shim.cu" -o "$TC_SHIM_OBJ"
    fi
}

# build_driver <out> <src> <flags...> — plain mojo build first, object+clang fallback second
# (setup_vm.sh's build_one_driver recipe; TC link args appended when flags carry the shim).
# The batched-serve driver additionally needs the attention_forge F32 twins on the include
# path (-I attention_forge), exactly the way its pre-TC campaign builds were made.
build_driver() {
    local out="$1"; shift
    local src="$1"; shift
    local want_tc=0 a
    for a in "$@"; do [[ "$a" == "ALGENTA_TC_SHIM" ]] && want_tc=1; done
    local tc_link=()
    if [[ "$want_tc" == "1" ]]; then
        tc_shim_object
        tc_link=(-Xlinker "$TC_SHIM_OBJ" -Xlinker -lcublas -Xlinker -lcudart \
                 -Xlinker "-L$CUDA_HOME/lib64")
    fi
    if "$MOJO" build "$@" ${tc_link[@]+"${tc_link[@]}"} \
        --target-accelerator "$SM_TARGET" \
        -I "$REPO_ROOT/mojo/engine" -I "$REPO_ROOT/attention_forge" \
        "$src" -o "$out" 2>/tmp/tc_drivers_build.log; then
        echo "[tc-drivers] built $(basename "$out") (plain build)"
        return 0
    fi
    echo "[tc-drivers] plain build refused: $(tail -2 /tmp/tc_drivers_build.log | head -1)"
    local max_lib pylib
    max_lib="$(dirname "$(find "$ENV_DIR" -name 'libMGPRT.so' | head -1)")"
    pylib="$(find "$ENV_DIR/lib" -maxdepth 1 -name 'libpython3*.so' | sort | head -1)"
    "$MOJO" build "$@" --target-accelerator "$SM_TARGET" \
        -I "$REPO_ROOT/mojo/engine" -I "$REPO_ROOT/attention_forge" \
        "$src" --emit object -o "$out.o" \
        || { tail -30 /tmp/tc_drivers_build.log; return 1; }
    local tc_clang=()
    if [[ "$want_tc" == "1" ]]; then
        tc_clang=("$TC_SHIM_OBJ" -L"$CUDA_HOME/lib64" -Wl,-rpath,"$CUDA_HOME/lib64"
                  -lcublas -lcudart)
    fi
    clang "$out.o" ${tc_clang[@]+"${tc_clang[@]}"} -o "$out" \
        -L"$max_lib" -Wl,-rpath,"$max_lib" \
        -lKGENCompilerRTShared -lAsyncRTRuntimeGlobals -lMSupportGlobals \
        -lAsyncRTMojoBindings -lMGPRT "$pylib" -lstdc++ -ldl -lpthread -lm
    echo "[tc-drivers] built $(basename "$out") (object+link recipe)"
}

NV="$REPO_ROOT/benchmarks/llm_smoke/nvidia_race"
# The campaign's batch-1 prefill levers (fixture/oracle path) and the s2l7 serve flags
# (REALRACE_RESULTS.md, "H100 CONCURRENT RE-MEASURE ON THE FIXED DRIVER").
B1_FLAGS=(-D ALGENTA_PF_ONEPASS_B1 -D ALGENTA_PF_ATTN_FLASH_B1 -D ALGENTA_PF_ATTN_FLASH2_B1)
SERVE_FLAGS=(-D ALGENTA_PF_ONEPASS -D ALGENTA_PF_ATTN_FLASH -D ALGENTA_P3_SERVE \
             -D ALGENTA_PF_STREAMS_2 -D ALGENTA_P3B_R2 -D ALGENTA_GRAPH_LANES)

for arm in $ARMS; do
    tc_flag=()
    suffix=""
    if [[ "$arm" == "tc" ]]; then
        tc_flag=(-D ALGENTA_TC_SHIM)
        suffix="_tc"
    fi
    echo "[tc-drivers] ══ arm: $arm ══"
    # fixture prefill bench (20-run median/IQR protocol, prefill phase timed)
    build_driver "$OUT_DIR/qwen3_bench_cuda_gen64$suffix" \
        "$REPO_ROOT/benchmarks/llm_smoke/qwen3_bench_cuda.mojo" \
        -D ALGENTA_GPU -D ALGENTA_CUDA "${B1_FLAGS[@]}" ${tc_flag[@]+"${tc_flag[@]}"}
    build_driver "$OUT_DIR/qwen3_generate_cuda$suffix" \
        "$REPO_ROOT/benchmarks/llm_smoke/qwen3_generate_cuda.mojo" \
        -D ALGENTA_GPU -D ALGENTA_CUDA "${B1_FLAGS[@]}" ${tc_flag[@]+"${tc_flag[@]}"}
    build_driver "$OUT_DIR/qwen3_p3_session_cuda$suffix" \
        "$NV/qwen3_p3_session_cuda.mojo" \
        -D ALGENTA_GPU -D ALGENTA_CUDA "${B1_FLAGS[@]}" ${tc_flag[@]+"${tc_flag[@]}"}
    build_driver "$OUT_DIR/qwen3_serve_batched_cuda$suffix" \
        "$NV/qwen3_serve_batched_cuda.mojo" \
        -D ALGENTA_GPU -D ALGENTA_CUDA "${SERVE_FLAGS[@]}" ${tc_flag[@]+"${tc_flag[@]}"}
    build_driver "$OUT_DIR/qwen25_7b_p3_graph_cuda$suffix" \
        "$NV/qwen25_7b_p3_graph_cuda.mojo" \
        -D ALGENTA_GPU -D ALGENTA_CUDA -D ALGENTA_STAGE_18944 \
        ${tc_flag[@]+"${tc_flag[@]}"}
done

chmod +x "$OUT_DIR"/qwen3_bench_cuda_gen64* "$OUT_DIR"/qwen3_generate_cuda* \
    "$OUT_DIR"/qwen3_p3_session_cuda* "$OUT_DIR"/qwen3_serve_batched_cuda* \
    "$OUT_DIR"/qwen25_7b_p3_graph_cuda* 2>/dev/null || true
echo "[tc-drivers] DONE — binaries in $OUT_DIR (arms: $ARMS, $SM_TARGET)"
