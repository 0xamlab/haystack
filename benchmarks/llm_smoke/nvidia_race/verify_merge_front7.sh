#!/usr/bin/env bash
# verify_merge_front7.sh — prove the merge of origin/main did not move the 7B path this round raced.
#
# WHY THIS IS NEEDED. main moved +885 lines into benchmarks/llm_smoke/nvidia_race/tc_shim.cu (the
# gemma-3 H200 rounds) and +6 entries into tc_shim_bridge.mojo while this round was measuring, so two
# of the four 7B-path files are no longer the bytes the raced binaries were built from:
#   tc_shim.cu          raced a862763133b7813fc598e0b1f1b6a989  -> merged 7e7f412d82aa06ef50d7fe84b6f57ec6
#   tc_shim_bridge.mojo raced 38926231b1058ab51f8c5943915b6573  -> merged fe510f8bdfa68216aab1f6f1f2250f5a
#   session_cuda_p3.mojo b73deffbeda21e165b9a5f111826da6f (unchanged)
#   qwen25_7b_p3_graph_cuda.mojo 30beeb9940c36523f36fbac8bc032f33 (unchanged)
# File bytes therefore CANNOT be the test — additive code in the same translation unit changes them
# by definition. The test that matters is the one this round already had to build for its own
# baseline: compile both sources from ONE neutral path and compare the per-kernel SASS digest of
# every kernel the 7B arms actually launch. If every shared kernel's machine code is identical, the
# raced cells still describe the merged tree; if any differs, they do not and must be re-taken.
#
# Then the empirical half: rebuild `_h0` and `_h1` from the merged tree and re-run one fixture cell
# each, which must reproduce the raced pp256/pp1024 medians and pass G0/G1.
set -uo pipefail
cd "$HOME/front7/repo" || exit 1
MEAS=${MEAS:-$HOME/trtllm/front7}
CUDA_HOME=${CUDA_HOME:-/usr/local/cuda}
SM=${SM:-sm_80}
PTXD=${PTXD:-/tmp/front7_ptxd_${SM}}
RACED=${RACED:-/tmp/f7_raced_tc_shim.cu}
NEUTRAL=/tmp/front7_verify
mkdir -p "$NEUTRAL" "$MEAS" "$PTXD"

echo "############ 0. re-staging after the boot (/tmp is wiped) ############"
mkdir -p /tmp/w7b/gate
ln -sfn "$HOME/trtllm/w7b_ckpt" /tmp/w7b/ckpt
sudo -n nvidia-smi -pm 1 >/dev/null 2>&1
sudo -n nvidia-smi -lgc 1410,1410 2>&1 | tail -1
nvidia-smi --query-gpu=clocks.sm,power.limit,temperature.gpu,memory.used --format=csv,noheader
if [[ ! -f /tmp/w7b/gate/ref_tokens.json ]]; then
    nohup python3 benchmarks/llm_smoke/nvidia_race/ref_transformers_cpu.py \
        --model-dir "$HOME/models/Qwen2.5-7B-Instruct" --ckpt /tmp/w7b/ckpt --n-tokens 16 \
        --cases fixture,chat --out /tmp/w7b/gate/ref_tokens.json \
        > "$MEAS/verify_oracle.log" 2>&1 &
    echo "  fixture+chat oracle regenerating in background (pid $!)"
fi
echo "  raced shim source md5: $(md5sum "$RACED" | cut -d' ' -f1)  (expect a862763133b7813fc598e0b1f1b6a989)"
echo "  merged shim source md5: $(md5sum benchmarks/llm_smoke/nvidia_race/tc_shim.cu | cut -d' ' -f1)"

echo "############ 1. per-kernel SASS: raced source vs merged source ############"
# The shim #includes an embedded-PTX header that the harness generates, and /tmp is wiped on every
# boot -- so calling nvcc directly without it fails with "tc_rt_ptx.h: No such file or directory",
# which a grep for "error" does not catch and which reads as an empty SASS dump (0 kernels compared,
# 0 differing) rather than as a build that never happened. Generate it first, and fail loudly if the
# objects do not appear.
if [[ ! -f "$PTXD/tc_rt_ptx.h" ]]; then
    mkdir -p "$PTXD"
    "$CUDA_HOME/bin/nvcc" -ptx -arch=compute_80 benchmarks/llm_smoke/nvidia_race/tc_rt_kernels.cu \
        -o "$PTXD/tc_rt_kernels.ptx" || { echo "PTX GEN FAILED"; exit 1; }
    python3 - "$PTXD/tc_rt_kernels.ptx" "$PTXD/tc_rt_ptx.h" <<'PYP'
import sys
data = open(sys.argv[1], "rb").read()
chunks = [",".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
with open(sys.argv[2], "w") as out:
    out.write("/* generated by verify_merge_front7.sh - embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
PYP
    echo "  generated $PTXD/tc_rt_ptx.h"
fi
build() { # out src
    cp "$2" "$NEUTRAL/tc_shim.cu"
    rm -f "$1"
    "$CUDA_HOME/bin/nvcc" -O3 -arch="$SM" -Xcompiler -fPIC -I"$PTXD" \
        -D ALGENTA_TC_SHIM_LT -D ALGENTA_TC_SHIM_O16 -c "$NEUTRAL/tc_shim.cu" -o "$1" \
        > "$MEAS/verify_build_$(basename "$1").log" 2>&1
    local rc=$?
    if [[ ! -s "$1" ]]; then
        echo "  BUILD FAILED for $1 (rc=$rc) -- tail of the log:"
        tail -6 "$MEAS/verify_build_$(basename "$1").log"
        exit 1
    fi
    echo "  built $1 rc=$rc ($(stat -c %s "$1") bytes)"
}
build /tmp/front7_verify_raced.o "$RACED"
build /tmp/front7_verify_merged.o benchmarks/llm_smoke/nvidia_race/tc_shim.cu
for o in /tmp/front7_verify_raced.o /tmp/front7_verify_merged.o; do
    "$CUDA_HOME/bin/cuobjdump" -sass "$o" > "$MEAS/verify_sass_$(basename "$o" .o).txt" 2>/dev/null
done
python3 - "$MEAS/verify_sass_front7_verify_raced.txt" "$MEAS/verify_sass_front7_verify_merged.txt" <<'PY'
"""Per-kernel SASS digest: raced source vs merged source. The 7B path must be untouched."""
import hashlib, re, sys

def kernels(path):
    out, name, body = {}, None, []
    for line in open(path, errors="replace"):
        m = re.search(r"Function : (.+)$", line)
        if m:
            if name:
                out[name] = hashlib.md5("\n".join(body).encode()).hexdigest()
            name, body = m.group(1).strip(), []
        elif name and re.match(r"\s+/\*[0-9a-f]+\*/", line):
            body.append(line.split("*/", 1)[-1].strip())
    if name:
        out[name] = hashlib.md5("\n".join(body).encode()).hexdigest()
    return out

raced, merged = kernels(sys.argv[1]), kernels(sys.argv[2])
shared = sorted(set(raced) & set(merged))
diff = [k for k in shared if raced[k] != merged[k]]
only_r = sorted(set(raced) - set(merged))
only_m = sorted(set(merged) - set(raced))
print(f"  kernels: raced={len(raced)} merged={len(merged)} shared={len(shared)} "
      f"DIFFERING={len(diff)}")
for k in diff:
    print("   DIFFERS:", k[:100])
print(f"  only in raced ({len(only_r)}): {[k[:60] for k in only_r][:6]}")
print(f"  only in merged ({len(only_m)}): {[k[:60] for k in only_m][:8]}")
# the kernels the 7B arms actually launch
SEVEN_B = ("_fa2_causal_kernel", "_fa2_causal_o16_kernel", "_fa_causal_kernel",
           "_swiglu_f16_fastexp_kernel", "_f32_to_f16_kernel", "_f32_to_f16_v8_kernel",
           "_verify_o16_kernel", "_f16_to_f32_kernel")
checked = [k for k in shared if any(s in k for s in SEVEN_B)]
bad = [k for k in checked if raced[k] != merged[k]]
missing = [s for s in SEVEN_B if not any(s in k for k in shared)]
print(f"  7B-path kernels compared: {len(checked)} | differing: {len(bad)} | "
      f"absent from both: {missing}")
for k in bad:
    print("   7B DIFFERS:", k[:100])
ok = not diff and not bad and not missing
print("MERGE_7B_SASS_NEUTRAL", "PASS" if ok else "FAIL")
sys.exit(0 if ok else 1)
PY
SASS_RC=$?

echo "############ 2. rebuild the raced arms from the merged tree ############"
cp benchmarks/llm_smoke/nvidia_race/tc_shim.cu /tmp/front7_proof/tc_shim.cu 2>/dev/null || true
PROOF=0 BUILD_ARMS=1 BUILD_ONLY="_h0 _h1" RUN_SWEEP=0 RUN_RAG=0 RUN_VERIFY=0 RUN_DIAG=0 \
    STAGE=9 bash benchmarks/llm_smoke/nvidia_race/run_ab_7b_front7.sh 2>&1 \
    | grep -E "BUILD_OK|BUILD_FAIL|O16_COPY_DRIFT|error" | head -10
echo "  raced binaries were: _h0 c622986040b29277b6306507d30fa88f  _h1 e53930f2b2677fbe5e20492f0d625aad"
echo "  rebuilt from merged tree:"
md5sum "$HOME/front7/bin/qwen25_7b_p3_graph_cuda_h0" "$HOME/front7/bin/qwen25_7b_p3_graph_cuda_h1"
echo "  (a different md5 here is EXPECTED — main's gemma-3 code is in the same object — which is"
echo "   exactly why step 1 compares per-kernel SASS rather than file bytes)"

echo "############ 3. one fixture cell per arm, to confirm the raced numbers reproduce ############"
for i in $(seq 1 120); do [[ -f /tmp/w7b/gate/ref_tokens.json ]] && break; sleep 10; done
ORACLE=$(python3 -c "
import json;r=json.load(open('/tmp/w7b/gate/ref_tokens.json'))
print(','.join(str(int(t)) for t in r['fixture']['generated_ids'][:16]))" 2>/dev/null)
echo "  oracle: ${ORACLE:-MISSING (G1 only)}"
for A in _h0 _h1; do
    for _ in $(seq 1 200); do
        [[ -z "$(nvidia-smi --query-compute-apps=pid --format=csv,noheader)" ]] && break; sleep 2
    done
    O=(); [[ -n "$ORACLE" ]] && O=(--oracle "$ORACLE")
    "$HOME/front7/bin/qwen25_7b_p3_graph_cuda${A}" --checkpoint /tmp/w7b/ckpt --arm p3 \
        "${O[@]}" --warmup 1 --runs 5 --out "$MEAS/verify_${A}.txt" \
        > "$MEAS/verify_${A}.log" 2>&1
    echo "  == $A rc=$?"
    grep -E "G0 RESULT|G1 RESULT|^prefill256|^prefill1024|^gen 256|DECLINED|o16_twin" \
        "$MEAS/verify_${A}.log" | head -8
done
echo "  raced fixture medians were: _h0 pp256 12796.05/12879.86  pp1024 15443.32/15445.19"
echo "                              _h1 pp256 12917.27            pp1024 15546.02"
nvidia-smi --query-gpu=clocks.sm,temperature.gpu,memory.used --format=csv,noheader
echo "VERIFY_MERGE_FRONT7_DONE sass_rc=$SASS_RC"
