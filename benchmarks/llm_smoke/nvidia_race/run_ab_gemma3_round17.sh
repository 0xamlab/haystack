#!/usr/bin/env bash
# run_ab_gemma3_round17.sh — RUN THIS ON THE VM. Round 17: the cublasLt ALGORITHM lever, ported
# from the 7B lane into gemma-3, gated and bracketed.
#
# ── WHAT IS BEING MEASURED, AND WHY THIS LEVER ────────────────────────────────────────────────
# Round 16's identity-based census re-ranked the levers by MEASURED pool instead of by campaign
# momentum. GEMM came first by a wide margin: 432.694 ms = 77.84% of region busy at rag4096, at
# 484.7 TFLOP/s = 68.8% of the 1410 MHz-pinned 989 TF/s peak. +5% of efficiency there is 21.6 ms,
# which ALONE clears the 12.07 ms the 1.15x bar needs. And unlike the wgmma route, its comparator
# is the same library on the same shapes rather than a cross-basis number.
#
# The lever is NOT a new kernel. `cublasGemmEx`'s per-call CUBLAS_GEMM_DEFAULT heuristic is an
# ESTIMATE; the shim's `tc_lt` namespace instead runs a TIMED SEARCH over the top-N cublasLt
# heuristics once per shape at stage time and caches the winner. gemm_probe had already measured
# winners that were not heuristic index 0, which is why the search is timed rather than taking
# result[0]. The 7B lane has carried this as `ALGENTA_7B_PF_LTALGO` since FRONT 6; gemma-3 had no
# cublasLt path at all, so round 17 ports it.
#
# ── THE TWO ARMS, AND WHY THEY DIFFER IN EXACTLY ONE RESPECT ──────────────────────────────────
#   R17_ctl  the SHIPPED DEFAULT (R6_STACK, no opt-outs, i.e. the R9_both configuration that is
#            default-ON since #1042). Passes NO lever flag, and links the STOCK shim object.
#   R17_lt   the shipped default + `-D ALGENTA_G3_PF_LTALGO`, linking the cublasLt-ENABLED shim
#            object and `-lcublasLt`.
#
# TWO SHIM OBJECTS, NOT ONE, AND THAT IS DELIBERATE. tc_shim.cu's cublasLt block has NO `#else`
# stubs, so an object built without `-D ALGENTA_TC_SHIM_LT` carries no `tc_lt` symbols at all. A
# control arm linked against that object therefore PROVABLY contains no part of the lever — not
# "contains it but does not reach it". The `verify` stage below re-checks this from the linked
# binaries with `nm`, so the claim is evidence rather than intent. The cost is one extra nvcc pass.
#
# The gemma-3 lane dispatches the seam-free `_async_lt` twins rather than the 7B lane's sync
# `_pre_lt` entries, because this lane runs with the shim's `g_noseam == 0` (it gets zero-sync
# ordering from `ALGENTA_G3_STREAM` instead). Reusing the 7B entries would have inserted a
# per-GEMM `cudaStreamSynchronize` the control arm does not have, and the bracket would then have
# measured a sync seam rather than an algorithm. See `matmul_async` in tc_shim.cu.
#
# ── PROTOCOL (the owner's, unchanged) ─────────────────────────────────────────────────────────
# Oracle gate BEFORE any speed claim on the changed arm (G0 16/16 + G1 64/64 greedy against the
# cache-free fp32 transformers oracle), plus the gate's own `rep2` bit-identical repeat. This lever
# is NOT bit-identical to the control by construction: a tuned algorithm may split K or tile
# differently, so the reduction order moves and the f32 accumulator rounds differently. That is
# exactly why the gate is a prerequisite rather than a formality. Then an interleaved A..B..A
# bracket whose drift armor is MEASURED from the closing cell — a delta that does not exceed its
# armor is NOT RESOLVED, not a win.
#
# ── STAGES ────────────────────────────────────────────────────────────────────────────────────
#   STAGE=build    both shims + both arms, then the nm verify. No GPU work.
#   STAGE=verify   re-run just the nm/sha audit on binaries that already exist.
#   STAGE=smoke    two pp1024 cells, proves the LT arm arms and prints its banner.
#   STAGE=gate     oracle gate on R17_lt (the changed arm), then on R17_ctl (re-earned here).
#   STAGE=timing   the interleaved bracket over PROMPTS.
#   STAGE=all      build -> verify -> smoke -> gate -> timing.
#
#   STAGE=build bash run_ab_gemma3_round17.sh
#   STAGE=gate  bash run_ab_gemma3_round17.sh
#   STAGE=timing MEAS_RUNS=5 bash run_ab_gemma3_round17.sh
set -uo pipefail

SM=${SM:-sm_90}
GPU=${GPU:-1}
SRC_TREE=${SRC_TREE:-$HOME/g3r17}         # the tree vm_sync_r17.sh materialises
CKPT=${CKPT:-/mnt/ramblob/g3conv27b}
L17=${L17:-$HOME/lever17}
L3=${L3:-$HOME/lever3}                     # cell_watchdog.sh + gate_any.py live here
CUDA_HOME=${CUDA_HOME:-/usr/local/cuda}
ENV_DIR=${ENV_DIR:-$HOME/algenta/mojo_env/.pixi/envs/default}
MOJO=${MOJO:-$ENV_DIR/bin/mojo}
export MODULAR_HOME=${MODULAR_HOME:-$ENV_DIR/share/max}
export CUDA_VISIBLE_DEVICES=$GPU

PTXD=${PTXD:-/tmp/g3r17tc}                 # tmpfs: wiped per stop, regenerated by the shim build
TC_STOCK=$PTXD/tc_shim.o
TC_LT=$PTXD/tc_shim_lt.o

STAGE=${STAGE:-all}
ARM=${ARM:-R17_lt}                         # the CHANGED arm, i.e. the one the gate must earn
ARM_A=${ARM_A:-R17_ctl}                    # bracket A = control = the shipped default
ARM_B=${ARM_B:-R17_lt}                     # bracket B = the lever
ARM_C=${ARM_C-}
CELLTAG=${CELLTAG:-_r17}                   # so this bracket's cells do not pool with round 6/9's
BUILD_ARMS=${BUILD_ARMS:-1}
PY=${PY:-/usr/bin/python3}

# The STOCK driver, outside the synced tree, exactly as rounds 7/9 used it — the driver is the
# harness, not the thing under test, and building the arms from an unmodified driver is what makes
# their hashes comparable with the certified R9_both family. Falls back to the in-tree copy if the
# VM's ~/adj was lost, and says so rather than silently changing basis.
DRIVER=${DRIVER:-$HOME/adj/build/driver_ctx8192.mojo}
if [[ ! -f "$DRIVER" ]]; then
  DRIVER=$SRC_TREE/benchmarks/llm_smoke/nvidia_race/vm_harness/adj/build/driver_ctx8192.mojo
  echo "NOTE: ~/adj/build/driver_ctx8192.mojo absent; using the in-tree copy at $DRIVER"
fi

BASE="-D ALGENTA_GPU -D ALGENTA_CUDA -D ALGENTA_STAGE_6144 -D ALGENTA_G3_GEGLU_U4 \
-D ALGENTA_TC_SHIM -D ALGENTA_G3_ATTN_FLASH -D ALGENTA_G3_PF_TCATTN -D ALGENTA_G3_STREAM"
R5_STACK="-D ALGENTA_G3_PF_FA -D ALGENTA_G3_PF_F16ATTN -D ALGENTA_G3_PF_F16NORM \
-D ALGENTA_G3_PF_F16MLP -D ALGENTA_G3_PF_ROPE2"
R6_STACK="$R5_STACK -D ALGENTA_G3_PF_FA2 -D ALGENTA_G3_PF_KV16 -D ALGENTA_G3_PF_BN32"

# Round 17 brackets the two cells whose projections all run at m = G3_PF_TILE = 1024, i.e. the two
# shapes the stage-time search actually tunes. pp256 is deliberately NOT in the default set: at
# m = 256 every dispatch declines (-320) to GemmEx DEFAULT, so the lever is a NULL there by
# construction and timing it would spend VM minutes on a foregone conclusion. Set
# PROMPTS_NULLCTL=1 to add it back as an explicit negative control if the cap allows.
DRIVER_PROMPTS=${PROMPTS:-"pp1024:/tmp/g3pp1024/prompt_0000.txt:1 rag4096:/tmp/g3rag/rag4096.txt:256"}
if [[ "${PROMPTS_NULLCTL:-0}" == "1" ]]; then
  DRIVER_PROMPTS="pp256:/tmp/g3pp256/prompt_0000.txt:1 $DRIVER_PROMPTS"
fi

mkdir -p "$L17/runs" "$L17/logs" "$L17/clocks" "$PTXD"
CW_LOGFILE=${CW_LOGFILE:-$L17/round17.log}
export CW_LOGFILE

ts() { date -u +%FT%TZ; }
log() { echo "[$(ts)] $*" | tee -a "$CW_LOGFILE"; }

build_shim() { # $1 = label ; $2 = object path ; $3 = extra macros (may be empty)
  log "=== shim $1 -> $2  extra=[$3] ==="
  PTXD="$PTXD" SM="$SM" CUDA_HOME="$CUDA_HOME" \
    NR="$SRC_TREE/benchmarks/llm_smoke/nvidia_race" \
    REGLOG="$L17/logs/ptxas_v_$1.log" \
    EXTRA_MACROS="$3" OBJNAME="$(basename "$2")" \
    bash "$SRC_TREE/benchmarks/llm_smoke/nvidia_race/build_shim_gemma3_round7.sh" \
    > "$L17/logs/nvcc_$1.log" 2>&1
  local rc=$?
  log "nvcc $1 rc=$rc bytes=$(stat -c %s "$2" 2>/dev/null)"
  grep -E "SHIM_FLAVOUR|RC_SHIM" "$L17/logs/nvcc_$1.log" | tee -a "$CW_LOGFILE"
  if (( rc != 0 )); then tail -40 "$L17/logs/nvcc_$1.log" | tee -a "$CW_LOGFILE"; return 1; fi
  # the register census is recorded either way: it is the standing evidence that the attention
  # kernels did not regress as a side effect of a shim rebuild.
  grep -E "peak registers|instantiations," "$L17/logs/nvcc_$1.log" | tail -3 | tee -a "$CW_LOGFILE"
  return 0
}

build_arm() { # $1 = name ; $2 = shim object ; $3 = extra linker libs ; rest = extra mojo flags
  local name=$1 shim=$2 libs=$3; shift 3
  local extra="$*"
  log "=== build $name : shim=$(basename "$shim") libs=[$libs] extra=[$extra] ==="
  ( cd "$SRC_TREE" && $MOJO build $BASE $extra \
      --target-accelerator "$SM" -I mojo/engine -I attention_forge \
      "$DRIVER" -o "$L17/$name" \
      -Xlinker "$shim" -Xlinker -lcublas $libs -Xlinker -lcudart \
      -Xlinker -L"$CUDA_HOME/lib64" ) > "$L17/logs/build_$name.log" 2>&1
  local rc=$?
  log "build $name rc=$rc bytes=$(stat -c %s "$L17/$name" 2>/dev/null)"
  if (( rc != 0 )) || [[ ! -x "$L17/$name" ]]; then
    tail -40 "$L17/logs/build_$name.log" | tee -a "$CW_LOGFILE"; return 1
  fi
  return 0
}

verify_arms() {
  # The binary-level audit. Three claims are checked from the linked executables themselves rather
  # than from the flags we intended to pass, because this campaign has already been burned once by
  # a rebuild that had silently dropped `-D ALGENTA_G3_STREAM` and produced a gemma-3-27b column
  # that was wrong at oracle index 0 on 5/6 prompts.
  #
  # NOTE ON nm: the shim object is linked IN, so `tc_shim_lt_tune` is a DEFINED symbol of the LT
  # arm rather than an undefined reference, and a stripped or statically-resolved binary may not
  # expose it through the dynamic table. So the symbol probe tries `nm`, then `nm -D`, then
  # `strings` on the symbol table, and takes the MAXIMUM — and if all three come back empty for
  # BOTH arms the probe is reported INCONCLUSIVE rather than silently read as "control is clean".
  log "=== VERIFY: what the two linked binaries actually carry ==="
  local a nl lit sym_tot=0
  for a in "$ARM_A" "$ARM_B"; do
    local b="$L17/$a"
    [[ -x "$b" ]] || { log "FATAL: $b missing — run STAGE=build"; return 1; }
    log "  $a sha256_16=$(sha256sum "$b" | cut -c1-16) bytes=$(stat -c %s "$b")"
    local n1 n2 n3
    n1=$(nm "$b" 2>/dev/null | grep -c "tc_shim_lt_tune\|_async_lt" || true)
    n2=$(nm -D "$b" 2>/dev/null | grep -c "tc_shim_lt_tune\|_async_lt" || true)
    n3=$(strings -a "$b" 2>/dev/null | grep -c "tc_shim_lt_tune\|_async_lt" || true)
    nl=$(( n1 > n2 ? (n1 > n3 ? n1 : n3) : (n2 > n3 ? n2 : n3) ))
    sym_tot=$(( sym_tot + nl ))
    log "  $a cublasLt symbol references = $nl   (nm=$n1 nm-D=$n2 strings=$n3)"
    lit=$(strings -a "$b" | grep -c "TCFLAG ALGENTA_G3_PF_LTALGO=1" || true)
    log "  $a LTALGO banner literal = $lit"
    if [[ "$a" == "$ARM_A" ]]; then
      # The control must carry NEITHER. A control that references the lever cannot bound it.
      if (( nl != 0 || lit != 0 )); then
        log "FATAL: the CONTROL arm $a carries part of the lever (lt syms=$nl, literal=$lit)."
        log "       The bracket would not bound the lever. Refusing to continue."
        return 1
      fi
      log "  $a VERIFIED CLEAN: no cublasLt symbol reference, no LTALGO banner literal"
    else
      if (( lit == 0 )); then
        log "FATAL: the LEVER arm $a carries no LTALGO banner literal. The macro did not reach"
        log "       the compiler; a declined lever must never masquerade as a measured one."
        return 1
      fi
      log "  $a VERIFIED ARMED: banner literal present, cublasLt symbol references = $nl"
    fi
  done
  if (( sym_tot == 0 )); then
    log "WARNING: the cublasLt SYMBOL probe read 0 for BOTH arms, including the lever arm. The"
    log "         banner literal still proves the macro reached the compiler, but the symbol probe"
    log "         is INCONCLUSIVE here (nm unavailable, or the binary is stripped). Recorded rather"
    log "         than papered over: the control's cleanliness then rests on the literal alone."
  fi
  return 0
}

if [[ "$STAGE" == "all" || "$STAGE" == "build" ]]; then
  build_shim stock "$TC_STOCK" "" || exit 1
  build_shim lt "$TC_LT" "-D ALGENTA_TC_SHIM_LT" || exit 1
  if (( BUILD_ARMS == 1 )); then
    # R17_ctl IS the shipped default: R6_STACK with no opt-outs, because ROPEVEC and GQA2 have been
    # default-ON since #1042, so the absence of flags IS the configuration. Stock shim, no -lcublasLt.
    build_arm "$ARM_A" "$TC_STOCK" "" $R6_STACK || exit 1
    # R17_lt adds exactly one macro and exactly one library.
    build_arm "$ARM_B" "$TC_LT" "-Xlinker -lcublasLt" $R6_STACK -D ALGENTA_G3_PF_LTALGO || exit 1
  fi
  verify_arms || exit 1
  log "STAGE=build complete"
  [[ "$STAGE" == "build" ]] && exit 0
fi

if [[ "$STAGE" == "verify" ]]; then
  verify_arms; exit $?
fi

# Everything below needs the GPU. The cells (watchdog, clock pinning, 1 Hz sampler, the interleaved
# bracket, the oracle gate) live in round 6's runner, reused UNMODIFIED — the protocol belongs in
# exactly one place and it is generic over ARM_*/BIN_DIR/MEAS.
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CELLS_SH=${CELLS_SH:-$HERE/run_gemma3_round6_cells.sh}
export BIN_DIR="$L17" MEAS="$L17" CW_LOGFILE

if [[ "$STAGE" == "all" || "$STAGE" == "smoke" ]]; then
  log "=== smoke: does the LT arm ARM, and what is the first delta? ==="
  STAGE=smoke ARM_A="$ARM_A" ARM_B="$ARM_B" ARM_C="$ARM_C" CELLTAG="$CELLTAG" \
    PROMPTS="pp1024:/tmp/g3pp1024/prompt_0000.txt:1" bash "$CELLS_SH" || exit 1
  # THE BANNER IS THE PROOF THE LEVER IS LIVE. Two things must both be true: the flag literal is
  # printed, AND `lt_shapes_tuned` is non-zero. A zero count means every dispatch declined (-320)
  # and the cell was timed on the shipped GemmEx path while still claiming the flag — the exact
  # silent-drop failure mode the banner exists to make unrepresentable.
  for a in "$ARM_B" "$ARM_A"; do
    log "--- $a smoke banner ---"
    grep -m1 "TCFLAG ALGENTA_G3_PF_LTALGO" "$L17/runs/smoke_${CELLTAG}_${a}_pp1024.out" 2>/dev/null \
      || grep -m1 "TCFLAG ALGENTA_G3_PF_LTALGO" "$L17"/runs/smoke_*"${a}"_pp1024.out 2>/dev/null \
      || echo "NOTE: no LTALGO banner for $a (EXPECTED for $ARM_A, FATAL for $ARM_B)"
    grep -E "gemma3-f16 LT: (tuned|PARTIAL)" "$L17"/runs/smoke_*"${a}"_pp1024.out 2>/dev/null | head -6 \
      | tee -a "$CW_LOGFILE"
  done
  if ! grep -q "lt_shapes_tuned = [1-9]" "$L17"/runs/smoke_*"${ARM_B}"_pp1024.out 2>/dev/null; then
    log "FATAL: $ARM_B tuned ZERO shapes. The lever declined everywhere; any timing would be a"
    log "       null bracket wearing the lever's name. Refusing to spend gate or timing minutes."
    exit 1
  fi
  log "smoke: $ARM_B tuned a non-zero number of shapes — the lever is LIVE"
fi

if [[ "$STAGE" == "all" || "$STAGE" == "gate" ]]; then
  log "=== oracle gate on $ARM (the CHANGED arm) — must pass before any speed claim ==="
  STAGE=gate ARM="$ARM" bash "$CELLS_SH" || {
    log "GATE FAILED on $ARM: no timing cells may be taken or published for this arm"; exit 1; }
  log "=== oracle gate on $ARM_A (the control, re-earned on THIS checkpoint) ==="
  STAGE=gate ARM="$ARM_A" bash "$CELLS_SH" || {
    log "GATE FAILED on $ARM_A: the checkpoint or the control is suspect, stop"; exit 1; }
  [[ "$STAGE" == "gate" ]] && exit 0
fi

if [[ "$STAGE" == "all" || "$STAGE" == "timing" ]]; then
  log "=== timing bracket A=$ARM_A B=$ARM_B C=$ARM_C PROMPTS=[$DRIVER_PROMPTS] ==="
  log "    armor protocol: 3 warmup + ${MEAS_RUNS:-7} measured + ${CLOSE_RUNS:-2} closing (A..B..A)"
  STAGE=timing ARM_A="$ARM_A" ARM_B="$ARM_B" ARM_C="$ARM_C" CELLTAG="$CELLTAG" \
    PROMPTS="$DRIVER_PROMPTS" bash "$CELLS_SH" || exit 1
  [[ "$STAGE" == "timing" ]] && exit 0
fi

log "STAGE=$STAGE complete"
