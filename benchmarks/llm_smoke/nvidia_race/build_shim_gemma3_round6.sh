#!/bin/bash
# build_shim_g3r6.sh -- build the round-6 tc_shim object the way run_ab_7b_front3.sh does: the
# shim #includes a GENERATED embedded-PTX header (tc_rt_ptx.h, from tc_rt_kernels.cu), so the
# header has to exist in the -I directory before tc_shim.cu will compile. Forgetting that costs a
# fatal error at the last step of a long chain (it did: chain5c's probe stage and chain5d's build
# both died on `tc_rt_ptx.h: No such file or directory` after an instance restart wiped /tmp).
set -uo pipefail
NR=${NR:-/home/angel/g3r6/benchmarks/llm_smoke/nvidia_race}
D=${PTXD:-/tmp/g3r6tc}
SM=${SM:-sm_90}
COMPUTE=${COMPUTE:-compute_90}
CUDA_HOME=${CUDA_HOME:-/usr/local/cuda}
mkdir -p "$D"
if [[ ! -f "$D/tc_rt_ptx.h" ]]; then
  echo "=== generating $D/tc_rt_ptx.h from tc_rt_kernels.cu ==="
  "$CUDA_HOME/bin/nvcc" -ptx -arch="$COMPUTE" "$NR/tc_rt_kernels.cu" -o "$D/tc_rt_kernels.ptx" || exit 1
  python3 - "$D/tc_rt_kernels.ptx" "$D/tc_rt_ptx.h" <<'PY' || exit 1
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
chunks = [",".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
with open(dst, "w") as out:
    out.write("/* generated by build_shim_g3r6.sh - embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
PY
fi
echo "=== nvcc tc_shim.cu -arch=$SM -I $D ==="
"$CUDA_HOME/bin/nvcc" -O3 -arch="$SM" -Xcompiler -fPIC -I "$D" \
  -c "$NR/tc_shim.cu" -o "$D/tc_shim.o"
rc=$?
echo "RC_SHIM=$rc bytes=$(stat -c %s "$D/tc_shim.o" 2>/dev/null)"
exit $rc
