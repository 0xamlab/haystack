#!/usr/bin/env bash
# run_ab_7b_front5.sh — pinned-clocks interleaved A/B for FRONT 5 (the second attempt to flip
# the RAG-4096 0.9436x loss vs TensorRT-LLM 1.2.1 without regressing pp256 / pp1024 / decode).
#
# The baseline here is FRONT 4's SHIP ARM `_e3` (KVTWIN + FA2 on top of round 3's `_d8`),
# rebuilt fresh from THIS branch — never a remembered number. Every FRONT-5 lever is a build
# flag that defaults OFF, so `_e3` is byte-for-byte round 4's adopted binary.
#
#   _e3  baseline   round 4's ship arm: _d8 + 7B_PF_KVTWIN + 7B_PF_FA2
#   _f1  _e3 + ALGENTA_7B_PF_ROPEVEC   lever 2: the vectorized, barrier-free
#                                      bias+RoPE+KV-write (`_pf_biasropewrt_vec_kernel`) —
#                                      one row per block instead of one head per block, float4
#                                      load/store via loadvec._ld4/_st4, and no shared-memory
#                                      staging or barrier at all (Qwen2.5-7B has no q/k norm, so
#                                      the scalar kernel's `xs` round trip only ever moved a
#                                      value 64 lanes sideways)
#
# NOT RACED, RECORDED IN THE LEDGER INSTEAD: FRONT 5 lever 1 was a GQA-packed flash attention
# (`tc_shim.cu`'s `_fa3_causal_kernel`, one CTA covering all g=7 query heads of one kv head so
# the K/V tile is fetched once per (row-block, kv-head) instead of seven times). It is correct —
# the on-device A-fragment layout probe passes and it matches the host double-precision
# reference at every raced shape including the odd tail — and it is SLOWER at every one of its
# six configurations (best 35.35 ms over the RAG-4096 FA block against FA2's 33.63-33.89 ms),
# so it is not wired into the session and no arm carries it. It stays in the tree behind
# `tc_shim_fa3_causal_async` with fa_probe's `fa3-*` engines so the refutation is reproducible.
#
# Protocol (rounds 2-4's, unchanged): one process per arm per cell; each cell is the driver's
# own median of --runs 20 with rel-IQR and outlier reporting; arms interleaved with the baseline
# bracketing the sweep as drift armor; clocks read before and after every cell; G0 (16/16 greedy
# tokens vs the fp32 transformers oracle) and G1 (64/64 self-consistency) run inside every bench
# process, so every cell in this sweep is gate-checked by construction.
#
# VRAM HYGIENE (owner rule): every arm is its own short-lived process — nothing is left resident
# between stages, and the GPU is drained to 0 MiB before the next arm is launched.
#
# Usage (on algenta-ent-a100, from the repo root):
#   bash run_ab_7b_front5.sh                       # build every arm + the interleaved sweep
#   BUILD_ARMS=0 RUN_SWEEP=0 RUN_RAG=1 RAG_ARMS="_e3 _f1" bash run_ab_7b_front5.sh
#   BUILD_ONLY="_f1" BUILD_ARMS=1 RUN_SWEEP=0 bash run_ab_7b_front5.sh   # compile check only
set -uo pipefail
SRC=benchmarks/llm_smoke/nvidia_race/qwen25_7b_p3_graph_cuda.mojo
SHIM=benchmarks/llm_smoke/nvidia_race/tc_shim.cu
RTK=benchmarks/llm_smoke/nvidia_race/tc_rt_kernels.cu
NV=${NV:-$HOME/front5/bin}
CKPT=${CKPT:-/tmp/w7b/ckpt}
MEAS=${MEAS:-$HOME/trtllm/front5}
RUNS=${RUNS:-20}
SM=${SM:-sm_80}
CUDA_HOME=${CUDA_HOME:-/usr/local/cuda}
ENV_DIR=${ENV_DIR:-$HOME/w7b/mojo_env/.pixi/envs/default}
MOJO=${MOJO:-$ENV_DIR/bin/mojo}
export MODULAR_HOME=${MODULAR_HOME:-$ENV_DIR/share/max}
TC_OBJ=${TC_OBJ:-/tmp/front5_tc_shim_${SM}.o}
PTXD=${PTXD:-/tmp/front5_ptxd_${SM}}
# round 2's adopted base + round 3's three adopted levers + round 4's two = FRONT 5's `_e3`
BASE="-D ALGENTA_GPU -D ALGENTA_CUDA -D ALGENTA_STAGE_18944 -D ALGENTA_PF_ONEPASS_B1 \
-D ALGENTA_PF_ATTN_FLASH_B1 -D ALGENTA_PF_ATTN_FLASH2_B1 -D ALGENTA_TC_NOSEAM \
-D ALGENTA_7B_PF_TCATTN -D ALGENTA_TC_SHIM -D ALGENTA_7B_PF_SM1P \
-D ALGENTA_7B_PF_F16NORM -D ALGENTA_7B_PF_F16MLP -D ALGENTA_7B_CTX8192 \
-D ALGENTA_7B_PF_FA -D ALGENTA_7B_PF_FASTEXP -D ALGENTA_7B_PF_BIASROPE"
E3="-D ALGENTA_7B_PF_KVTWIN -D ALGENTA_7B_PF_FA2"

mkdir -p "$NV" "$MEAS" "$PTXD"

ORACLE=$(python3 - <<'PY'
import json
ref = json.load(open("/tmp/w7b/gate/ref_tokens.json"))
print(",".join(str(int(t)) for t in ref["fixture"]["generated_ids"][:16]))
PY
)

build_shim() {
    # the shim #includes the embedded-PTX header build_tc_drivers.sh's recipe generates
    if [[ ! -f "$PTXD/tc_rt_ptx.h" ]]; then
        "$CUDA_HOME/bin/nvcc" -ptx -arch=compute_80 "$RTK" -o "$PTXD/tc_rt_kernels.ptx" || return 1
        python3 - "$PTXD/tc_rt_kernels.ptx" "$PTXD/tc_rt_ptx.h" <<'PY' || return 1
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
chunks = []
for i in range(0, len(data), 24):
    chunks.append(",".join(str(b) for b in data[i:i + 24]))
with open(dst, "w") as out:
    out.write("/* generated by run_ab_7b_front5.sh - embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
PY
    fi
    echo "== nvcc tc_shim.cu -> $TC_OBJ"
    rm -f "$TC_OBJ"
    "$CUDA_HOME/bin/nvcc" -O3 -arch="$SM" -Xcompiler -fPIC -I"$PTXD" -Xptxas -v \
        -c "$SHIM" -o "$TC_OBJ" 2>&1 \
        | grep -E "error|_fa_causal_kernel|_fa2_causal_kernel|_fa3_causal_kernel|registers|spill" \
        | head -60
    [[ -f "$TC_OBJ" ]] || { echo "SHIM BUILD FAIL"; return 1; }
}

build_arm() { # suffix extra-flags...
    local suf="$1"; shift
    # shellcheck disable=SC2086
    "$MOJO" build $BASE "$@" --target-accelerator "$SM" -I mojo/engine -I attention_forge \
        "$SRC" -o "$NV/qwen25_7b_p3_graph_cuda${suf}" \
        -Xlinker "$TC_OBJ" -Xlinker -lcublas -Xlinker -lcudart -Xlinker "-L$CUDA_HOME/lib64" \
        > "$MEAS/build_${suf}.log" 2>&1 \
        && echo "BUILD_OK $suf" || { echo "BUILD_FAIL $suf (tail):"; tail -25 "$MEAS/build_${suf}.log"; return 1; }
}

wait_gpu_idle() {
    for _ in $(seq 1 300); do
        [ -z "$(nvidia-smi --query-compute-apps=pid --format=csv,noheader)" ] && return 0
        sleep 2
    done
    return 1
}

run_arm() { # suffix [extra driver args...]
    local suf="$1"; shift
    wait_gpu_idle || echo "WARN: gpu not idle before $suf"
    local c0 c1 t0 t1
    c0=$(nvidia-smi --query-gpu=clocks.sm --format=csv,noheader)
    t0=$(date +%s)
    "$NV/qwen25_7b_p3_graph_cuda${suf}" --checkpoint "$CKPT" --arm p3 "$@" \
        > "$MEAS/bench_${suf}$EXTRA_TAG.log" 2>&1
    local rc=$?
    t1=$(date +%s)
    c1=$(nvidia-smi --query-gpu=clocks.sm --format=csv,noheader)
    local mused
    mused=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader)
    echo "== ${suf}${EXTRA_TAG} rc=$rc wall=$((t1 - t0))s clocks=${c0}->${c1} vram_after=${mused}"
    grep -E "^prefill|^gen |G0 RESULT|G1 RESULT|STAGED|TC FLAGS|TCFLAG|ARMED|DECLINED" \
        "$MEAS/bench_${suf}${EXTRA_TAG}.log" | head -28
}

want_arm() { case " ${BUILD_ONLY:-_e3 _f1} " in *" $1 "*) return 0;; esac; return 1; }

if [ "${BUILD_ARMS:-1}" = "1" ]; then
    build_shim || exit 1
    # shellcheck disable=SC2086
    want_arm _e3 && build_arm _e3 $E3
    # shellcheck disable=SC2086
    want_arm _f1 && build_arm _f1 $E3 -D ALGENTA_7B_PF_ROPEVEC
fi

# ── the interleaved pp256/pp1024/decode sweep, baseline first and last (drift armor) ──
if [ "${RUN_SWEEP:-1}" = "1" ]; then
  for suf in ${ARMS:-_e3 _f1 _e3}; do
    EXTRA_TAG="_ra${ROUND:-1}"
    run_arm "$suf" --oracle "$ORACLE" --runs "$RUNS" \
        --out "$MEAS/bench_${suf}${EXTRA_TAG}.txt"
  done
fi

# ── RAG-4096: the three token-exact 4096-token prompts, long-context arms ──
if [ "${RUN_RAG:-0}" = "1" ]; then
  for suf in ${RAG_ARMS:-_e3 _f1}; do
    for i in ${RAG_PROMPTS:-0 1 2}; do
      IDS=$(python3 - "$i" <<'PY'
import json, sys
p = json.load(open("/home/angel/trtllm/prompts.json"))
print(",".join(str(int(t)) for t in p["rag"][int(sys.argv[1])]["ids"]))
PY
      )
      EXTRA_TAG="_rag${i}"
      run_arm "$suf" --prompt-ids "$IDS" --runs "$RUNS" \
          --out "$MEAS/rag${i}_${suf}.txt"
    done
  done
fi
echo "AB_FRONT5_DONE"
