#!/bin/bash
# build_shim_gemma3_round7.sh — round-7 tc_shim build. Same shape as build_shim_gemma3_round6.sh
# (the shim #includes a GENERATED embedded-PTX header, tc_rt_ptx.h, so that header must exist in
# the -I directory before tc_shim.cu will compile — forgetting it costs a fatal error at the last
# step of a long chain, and it has bitten chain5c, chain5d and the round-6 re-stage alike).
#
# THE ROUND-7 ADDITION IS `-Xptxas -v`. v3's whole risk is REGISTERS: qa[RT][8][4] +
# oacc[RT][16][4] + s[RT][NT][4] is ~112 registers per thread at RT=1 and ~224 at RT=2 against a
# 255 ceiling at __launch_bounds__(128). If nvcc spills to local memory the lever is dead on
# arrival and no timing is worth taking, so the register/spill census is produced by the BUILD and
# read BEFORE the probe runs. `--reg-census` below prints it per v3 instantiation.
set -uo pipefail
NR=${NR:-/home/angel/g3r7/benchmarks/llm_smoke/nvidia_race}
D=${PTXD:-/tmp/g3r7tc}
SM=${SM:-sm_90}
COMPUTE=${COMPUTE:-compute_90}
CUDA_HOME=${CUDA_HOME:-/usr/local/cuda}
REGLOG=${REGLOG:-$HOME/lever7/logs/ptxas_v.log}
# ROUND 17 additions, both defaulting to this script's previous behaviour so rounds 5/6/7/9 are
# byte-for-byte unaffected:
#   EXTRA_MACROS  extra -D flags for tc_shim.cu. Round 17 needs `-D ALGENTA_TC_SHIM_LT` to compile
#                 the cublasLt block in; WITHOUT it the object carries no `tc_lt` symbols at all
#                 (tc_shim.cu deliberately has NO `#else` stubs), which is what lets a baseline arm
#                 prove it carries no part of the lever rather than merely not reaching it.
#   OBJNAME       output object name, so a stock and an LT-enabled shim can coexist in one $D. They
#                 share the generated tc_rt_ptx.h (that header is macro-independent) but must not
#                 overwrite each other's .o.
EXTRA_MACROS=${EXTRA_MACROS:-}
OBJNAME=${OBJNAME:-tc_shim.o}
mkdir -p "$D" "$(dirname "$REGLOG")"
if [[ ! -f "$D/tc_rt_ptx.h" ]]; then
  echo "=== generating $D/tc_rt_ptx.h from tc_rt_kernels.cu ==="
  "$CUDA_HOME/bin/nvcc" -ptx -arch="$COMPUTE" "$NR/tc_rt_kernels.cu" -o "$D/tc_rt_kernels.ptx" || exit 1
  python3 - "$D/tc_rt_kernels.ptx" "$D/tc_rt_ptx.h" <<'PY' || exit 1
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
chunks = [",".join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
with open(dst, "w") as out:
    out.write("/* generated by build_shim_gemma3_round7.sh - embedded PTX */\n")
    out.write("static const unsigned char g_tc_rt_ptx[] = {\n")
    out.write(",\n".join(chunks))
    out.write(",0};\n")
PY
fi
echo "=== nvcc tc_shim.cu -arch=$SM -I $D -Xptxas -v ${EXTRA_MACROS:+$EXTRA_MACROS }-> $OBJNAME ==="
# $EXTRA_MACROS is deliberately unquoted: it is a space-separated list of -D flags that must word
# split into separate argv entries. It is empty by default, in which case the command line is
# identical to this script's pre-round-17 form.
# shellcheck disable=SC2086
"$CUDA_HOME/bin/nvcc" -O3 -arch="$SM" -Xcompiler -fPIC -I "$D" -Xptxas -v $EXTRA_MACROS \
  -c "$NR/tc_shim.cu" -o "$D/$OBJNAME" 2> "$REGLOG"
rc=$?
echo "RC_SHIM=$rc bytes=$(stat -c %s "$D/$OBJNAME" 2>/dev/null) reglog=$REGLOG"
if (( rc != 0 )); then
  echo "--- last 60 lines of the ptxas/nvcc log ---"
  tail -60 "$REGLOG"
  exit $rc
fi
# ROUND 17: prove which shim flavour was just built, from the object itself rather than from the
# command line we intended to run. The cublasLt block has NO `#else` stubs, so the presence or
# absence of `tc_shim_lt_tune` is a definitive, binary-level statement about whether an arm linked
# against this object can reach the lever at all.
if nm "$D/$OBJNAME" 2>/dev/null | grep -q "tc_shim_lt_tune"; then
  echo "SHIM_FLAVOUR=cublasLt-ENABLED (tc_shim_lt_tune present) obj=$OBJNAME"
else
  echo "SHIM_FLAVOUR=STOCK (no tc_lt symbols; a Mojo arm carrying ALGENTA_G3_PF_LTALGO or"
  echo "               ALGENTA_7B_PF_LTALGO will FAIL TO LINK against this object, by design)"
fi
# ── the register/spill census for the round-7 kernel, printed by the build so the decision does
#    not wait on a timing run. `spill` non-zero at RT=2 means the lever is dead on arrival. ──
echo "=== --reg-census: v3 (_fa_g3_window3_kernel) register + spill per instantiation ==="
python3 - "$REGLOG" <<'PY'
import re, sys
txt = open(sys.argv[1], errors="replace").read()
# ptxas -v emits a "Compiling entry function '...' for 'sm_90'" line then "Used N registers, ..."
ents = re.split(r"Compiling entry function ", txt)
rows = []
for e in ents[1:]:
    name = e.split("'")[1] if "'" in e else "?"
    if "_fa_g3_window3_kernel" not in name and "_fa_g3_window2_kernel" not in name:
        continue
    regs = re.search(r"Used (\d+) registers", e)
    spill = re.search(r"(\d+) bytes spill stores", e)
    smem = re.search(r"(\d+) bytes smem", e)
    cmem = re.search(r"(\d+) bytes cmem\[0\]", e)
    rows.append((name, int(regs.group(1)) if regs else -1,
                 int(spill.group(1)) if spill else 0,
                 int(smem.group(1)) if smem else 0,
                 int(cmem.group(1)) if cmem else 0))
if not rows:
    print("NO v2/v3 ENTRIES FOUND in the ptxas log — the census is INCONCLUSIVE, not a pass")
    sys.exit(0)
rows.sort(key=lambda r: (r[0].count("window3") == 0, r[0]))
print(f"{'kernel instantiation':<110} {'regs':>5} {'spillB':>7} {'smemB':>7}")
bad = 0
for name, regs, spill, smem, cmem in rows:
    tag = ""
    if spill > 0:
        tag = "   <-- SPILLS"
        bad += 1
    elif regs > 232:
        tag = "   <-- near the 255 ceiling"
    short = name if len(name) <= 110 else "..." + name[-107:]
    print(f"{short:<110} {regs:>5} {spill:>7} {smem:>7}{tag}")
print(f"--- {len(rows)} instantiations, {bad} with non-zero spill ---")
PY
exit 0
