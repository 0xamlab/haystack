#!/usr/bin/env python3
"""check_fixtures.py -- prove the REGENERATED prompt fixtures are token-identical to the ones
the pre-stop oracle gate certified, and write a marker file chain5c.sh gates on.

Why this exists: the instance stop/start wiped the tmpfs, so /tmp/g3pp256, /tmp/g3pp1024,
/tmp/g3race500 and /tmp/g3rag were regenerated by trtllm_prep.sh from the same deterministic
generator, seeds and lengths. "Same recipe" is a claim, not evidence. The evidence is that every
driver run echoes the exact prompt id list it ingested in its JSON, so the pre-stop gate cells in
~/lever5/runs/gate_*.out carry the ORIGINAL ids -- comparing the regenerated files against those
echoes is a direct token-for-token check with no re-derivation.

Exits 0 and writes FIXTURES_OK only when every fixture matches. Anything else exits 1: measuring
against a prompt set that differs from the gated one is a different experiment from the one the
oracle certified, and the chain must stop rather than publish it.
"""
import json
import sys
from pathlib import Path

RUNS = Path("/home/angel/lever5/runs")
MARKER = Path("/home/angel/lever5/FIXTURES_OK")
PAIRS = [
    ("gate_pp256_maxnew16",   "/tmp/g3pp256/prompt_0000.txt",  256),
    ("gate_pp1024_maxnew16",  "/tmp/g3pp1024/prompt_0000.txt", 1024),
    ("gate_val550_maxnew16",  "/tmp/g3race500/prompt_0000.txt", 550),
    ("gate_rag4096_maxnew64", "/tmp/g3rag/rag4096.txt",        4096),
]


def last_json(path):
    for line in reversed(path.read_text(errors="replace").splitlines()):
        line = line.strip()
        if line.startswith("{") and '"generated"' in line:
            try:
                return json.loads(line)
            except Exception:
                pass
    return {}


def read_ids(path):
    txt = Path(path).read_text(errors="replace").strip()
    return [int(x) for x in txt.replace(",", " ").split()]


def main():
    MARKER.unlink(missing_ok=True)
    ok = True
    for cell, fixture, want_n in PAIRS:
        out = RUNS / f"{cell}.out"
        if not out.exists():
            print(f"  {cell:<24} NO PRE-STOP REFERENCE ({out}) -- cannot verify")
            ok = False
            continue
        if not Path(fixture).exists():
            print(f"  {cell:<24} FIXTURE MISSING ({fixture})")
            ok = False
            continue
        echoed = last_json(out).get("prompt")
        got = read_ids(fixture)
        if echoed is None:
            print(f"  {cell:<24} pre-stop JSON carries no prompt echo -- cannot verify")
            ok = False
            continue
        same = (list(echoed) == got)
        ok = ok and same
        print(f"  {cell:<24} regenerated {len(got):>5} ids vs pre-stop echo {len(echoed):>5} ids "
              f"(expected {want_n:>5}) -> {'IDENTICAL' if same else 'DIFFERENT'}")
        if not same:
            d = next((i for i in range(min(len(got), len(echoed))) if got[i] != echoed[i]), None)
            print(f"      first difference at index {d}: regenerated "
                  f"{got[d] if d is not None and d < len(got) else None} vs pre-stop "
                  f"{echoed[d] if d is not None and d < len(echoed) else None}")
        if len(got) != want_n:
            print(f"      WARNING: length {len(got)} != the cell's nominal {want_n}")
    print("FIXTURE_IDENTITY_OK =", ok)
    if ok:
        MARKER.write_text("ok\n")
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
