                    ("ss_quantity", "sum"),
                    ("ss_quantity", "count"),
                    ("ss_quantity_sq", "sum"),
                    ("sr_return_quantity", "sum"),
                    ("sr_return_quantity", "count"),
                    ("sr_return_quantity_sq", "sum"),
                    ("cs_quantity", "sum"),
                    ("cs_quantity", "count"),
                    ("cs_quantity_sq", "sum"),
