    def stats(sum_x, n, sum_x2):
        if n <= 0:
            return None, None, None
        avg = sum_x / n
        if n <= 1:
            return n, avg, None
        var = (sum_x2 - (sum_x * sum_x) / n) / (n - 1)
        var = max(var, 0.0)
        return n, avg, var**0.5

    final = []
