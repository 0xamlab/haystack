# ── Q91: catalog_returns fact + a customer-DIMENSION resolve (2-branch OR) ─────
def q91():
    t0 = time.perf_counter()
    date_ok_rows = [
        [r["d_date_sk"]]
        for r in pg_fetch("SELECT d_date_sk FROM date_dim WHERE d_year=2000 AND d_moy=12")
    ]
    cc_ok_rows, cc_code_map = dim_with_code(
        "cc_call_center_sk", ["cc_call_center_id", "cc_name", "cc_manager"], "call_center"
    )
    # Dimension-to-dimension resolve ONLY (customer + its own demo/hdemo/addr
    # dimensions) -- no fact table involved, see engine_harness.py's docstring.
    cust_recs = pg_fetch(
        """
        SELECT c.c_customer_sk AS c_customer_sk,
               CASE WHEN cd.cd_marital_status='M' THEN 0.0 ELSE 1.0 END AS branch_code
        FROM customer c
        JOIN customer_demographics cd ON cd.cd_demo_sk = c.c_current_cdemo_sk
        JOIN household_demographics hd ON hd.hd_demo_sk = c.c_current_hdemo_sk
        JOIN customer_address ca ON ca.ca_address_sk = c.c_current_addr_sk
        WHERE ((cd.cd_marital_status='M' AND cd.cd_education_status='Unknown')
            OR (cd.cd_marital_status='W' AND cd.cd_education_status='Advanced Degree'))
          AND hd.hd_buy_potential LIKE 'Unknown%%'
          AND ca.ca_gmt_offset = -7
        """
    )
    cust_ok_rows = [[r["c_customer_sk"], r["branch_code"]] for r in cust_recs]
    branch_map = {0.0: ("M", "Unknown"), 1.0: ("W", "Advanced Degree")}

