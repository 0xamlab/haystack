# ── Q7/Q26: 5-way join, 4 averages GROUP BY i_item_id (a possibly-SCD string) ──
def _avg_by_item(
    qnum, date_fk, item_fk, cdemo_fk, promo_fk, year, cdemo_where, promo_where, fact_table, measures
):
    t0 = time.perf_counter()
    date_ok_rows = [
        [r["d_date_sk"]] for r in pg_fetch(f"SELECT d_date_sk FROM date_dim WHERE d_year = {year}")
    ]
    cdemo_ok_rows = [
        [r["cd_demo_sk"]]
        for r in pg_fetch(f"SELECT cd_demo_sk FROM customer_demographics WHERE {cdemo_where}")
    ]
    promo_ok_rows = [
        [r["p_promo_sk"]] for r in pg_fetch(f"SELECT p_promo_sk FROM promotion WHERE {promo_where}")
    ]
    item_ok_rows, item_code_map = dim_with_code("i_item_sk", ["i_item_id"], "item")

    fact_cols = [date_fk, item_fk, cdemo_fk, promo_fk] + measures
    fact = pg_fetch(f"SELECT {', '.join(fact_cols)} FROM {fact_table}")
    t1 = time.perf_counter()

    aggs = []
    for m in measures:
        aggs += [(m, "sum"), (m, "count")]

    sums, counts = {}, {}
    for batch in chunk(fact):
        rows = [[r[c] for c in fact_cols] for r in batch]
        q = (
            Query(columns=fact_cols, rows=rows)
            .with_table("date_ok", ["d_date_sk"], rows=date_ok_rows)
            .with_table("cdemo_ok", ["cd_demo_sk"], rows=cdemo_ok_rows)
            .with_table("promo_ok", ["p_promo_sk"], rows=promo_ok_rows)
            .with_table("item_ok", ["i_item_sk", "grp_code"], rows=item_ok_rows)
            .join("date_ok", left_on=date_fk, right_on="d_date_sk", how="semi")
            .join("cdemo_ok", left_on=cdemo_fk, right_on="cd_demo_sk", how="semi")
            .join("promo_ok", left_on=promo_fk, right_on="p_promo_sk", how="semi")
            .join("item_ok", left_on=item_fk, right_on="i_item_sk", how="inner")
            .group_by_many(by=["item_ok.grp_code"], aggs=aggs)
        )
        for r in run_query(q).rows:
            code = r[0]
            idx = 1
            for m in measures:
                s, c = r[idx], r[idx + 1]
                idx += 2
                sums.setdefault(m, {})
                counts.setdefault(m, {})
                sums[m][code] = sums[m].get(code, 0.0) + (s or 0.0)
                counts[m][code] = counts[m].get(code, 0.0) + (c or 0.0)
    t2 = time.perf_counter()

    all_codes = set()
    for m in measures:
        all_codes |= set(sums[m].keys())
    final = []
    for code in all_codes:
        item_id = _strip(item_code_map[code][0])
        avgs = [
            (sums[m].get(code, 0.0) / counts[m][code]) if counts[m].get(code, 0.0) else None
            for m in measures
        ]
        final.append((item_id, *avgs))
    final.sort(key=lambda t: t[0])
    final = final[:100]

    cols, drows, dt = duck_run(f"{TRANSLATED_QUERIES_DIR}/{qnum}.sql")
    mism = 0
    for e, d in zip(final, drows, strict=False):
        ok = e[0] == _strip(d[0]) and all(_close(e[i], d[i]) for i in range(1, 5))
        if not ok:
            mism += 1
    ok = mism == 0 and len(final) == len(drows)
    return (
        ok,
        f"engine_n={len(final)} duckdb_n={len(drows)} mismatches={mism} fetch={t1 - t0:.2f}s engine={t2 - t1:.2f}s duckdb={dt * 1000:.1f}ms",
    )


