"""The declared-capability manifest must actually SHIP, and must not invent a claim.

`algenta.capabilities` reads every capability field except `count_relations` from the bundled
`runtime_capability_manifest.json`. That resource was referenced by the surface, generated by
nothing and bundled by nothing, so `manifest_present` was False and every field of every
function reported `UNDECLARED` forever — indistinguishable from a tree nobody had annotated,
while the declarations sat in the kernels' own docstrings unread.

Nothing caught it because every other test injects `manifest_payload=`, and the two assertions
that touch the real package sit behind `if not catalog.manifest_present:` — so the suite was
green *because* the artifact was missing. These tests read the SHIPPED artifact with no
injection, so its absence or staleness is a failure here.

The second half is the harder property: the artifact is a TRANSCRIPTION of the kernels' blocks,
so a field nobody declared must be ABSENT from it, never written out as `false`. "We have not
said" and "we have said no" are different answers, and an artifact that collapses them makes
every consumer's answer wrong in the direction of over-claiming.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parent.parent
_ALGENTA = _REPO_ROOT / "packages" / "algenta"
for _path in (str(_REPO_ROOT), str(_ALGENTA)):
    if _path not in sys.path:
        sys.path.insert(0, _path)

from algenta.capabilities import (  # noqa: E402
    CAPABILITY_FIELDS,
    UNDECLARED,
    CapabilityError,
    capabilities,
)

sys.path.append(str(_REPO_ROOT / "scripts"))
from generate_algenta_capability_manifest import (  # noqa: E402
    DEFAULT_OUTPUT,
    EMITTED_FIELDS,
    build_manifest,
)

MANIFEST_PATH = _ALGENTA / "algenta" / "runtime_capability_manifest.json"
RESOURCE_NAME = "runtime_capability_manifest.json"


@pytest.fixture(scope="module")
def artifact() -> dict:
    assert MANIFEST_PATH.is_file(), (
        f"{MANIFEST_PATH} is missing. Run `make inventory-refresh`. Without it every declared "
        "capability field reads as UNDECLARED, which is indistinguishable from a tree nobody "
        "annotated."
    )
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def engine_blocks() -> dict[tuple[str, str], dict]:
    """The kernels' own declared blocks — the source of truth this artifact transcribes."""
    from apps.runtime.mojo_inventory import build_capability_manifest

    manifest = build_capability_manifest(strict=True)
    blocks: dict[tuple[str, str], dict] = {}
    for module in manifest.modules:
        for spec in module.functions:
            blocks[(module.import_path, spec.target)] = {
                name: getattr(spec, name, None) for name in EMITTED_FIELDS
            }
    return blocks


# ── it ships, and it is current ───────────────────────────────────────────────


def test_the_generated_path_is_inside_the_package(artifact) -> None:
    assert DEFAULT_OUTPUT == MANIFEST_PATH
    assert artifact["schema_version"] == 1


def test_the_shipped_artifact_is_not_stale() -> None:
    """`make inventory-check` runs this same comparison in CI; assert it here too.

    A stale manifest is the failure this whole file exists to prevent, one step milder: the
    declarations are read, they are just no longer the declarations in the kernels.
    """
    payload, _unreachable = build_manifest()
    expected = json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n"
    assert MANIFEST_PATH.read_text(encoding="utf-8") == expected, (
        "the bundled capability manifest does not match the kernels' declared blocks; run "
        "`make inventory-refresh`"
    )


