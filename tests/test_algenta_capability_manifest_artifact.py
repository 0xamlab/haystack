def test_the_wheel_declares_the_resource_as_package_data() -> None:
    """A generated resource that setuptools does not ship reaches no installed user.

    `scripts/verify_sdk_artifact_install.py` proves the built wheel really carries it; this
    catches the packaging half without building anything.
    """
    payload = tomllib.loads((_ALGENTA / "pyproject.toml").read_text(encoding="utf-8"))
    package_data = payload["tool"]["setuptools"]["package-data"]["algenta"]
    assert RESOURCE_NAME in package_data, package_data
    # The contract must keep shipping too — count relations travel on it.
    assert "runtime_library_contract.json" in package_data


def test_the_surface_reads_the_shipped_artifact_with_no_injection() -> None:
    catalog = capabilities()
    assert catalog.manifest_present is True, (
        "the package ships no capability manifest, so every declared field reads as "
        "UNDECLARED"
    )
    assert catalog.declaration_source == RESOURCE_NAME
    assert catalog.orphan_declarations == (), (
        "the manifest names functions the contract does not export; a declaration nobody can "
        "reach is a stale artifact"
    )


def test_a_declared_kernel_reports_its_declared_fields() -> None:
    """`stats.compute_mean` is the function whose unguarded count aborted a worker.

    Values are compared against `mojo/engine/stats.mojo`'s own block via `engine_blocks`
    elsewhere; the point here is that the SURFACE returns them rather than `UNDECLARED`.
    """
    record = capabilities().describe("stats", "compute_mean")
    assert record.has_block is True
    assert record.deterministic is True
    assert record.complexity == "O(n)"
    assert record.backend == "mojo"
    assert record.version_introduced == "pre_manifest"
    assert "library_execute" in record.surfaces
    # Count relations travel on the library contract, not on this artifact, and must still
    # arrive — they are the one field with a caller-facing consequence.
    assert record.count_relations is not UNDECLARED
    assert record.count_relations[0].expression == "n <= len(v)"
    assert record.undeclared_fields() == ()


def test_the_documented_search_snippet_returns_something() -> None:
    """`gitbook/engine/capabilities.md`'s worked example returned 0 matches / 137 undeclared.

    A documented loop that never executes is worse than no example, because a reader concludes
    the capability does not exist.
    """
    catalog = capabilities()
    found = catalog.search(module_prefix="optimization.", deterministic=True)
    assert len(found) > 0, found
    assert all(record.deterministic is True for record in found)
    complexities = [record.complexity for record in found if record.complexity is not UNDECLARED]
    assert complexities, "every match reported an undeclared complexity"
    record = catalog.describe("optimization.linear", "lp_solve_default")
    assert record.has_block is True
    assert "deterministic" in record.declared_fields()


# ── it does not invent a claim ────────────────────────────────────────────────


def test_every_emitted_field_is_one_the_kernel_actually_declared(artifact, engine_blocks) -> None:
    """The transcription rule: absent in the source block => absent in the artifact.

    This is the assertion that would fail if the generator ever routed through
    `apps.runtime.mojo_capability_manifest.resolved_claims`, which reads an undeclared
    `deterministic` as `false` on purpose for a scheduler that must decide something. Baking
    that collapse into a shipped artifact would make "the author said no" unreadable.
    """
    checked = 0
    for module in artifact["modules"]:
        for function in module["functions"]:
            key = (module["name"], function["name"])
            declared = engine_blocks.get(key)
            assert declared is not None, f"{key} is in the artifact but declares no block"
            for name, value in function["capability"].items():
                source_value = declared.get(name)
                assert source_value is not None, (
                    f"{key}.{name} = {value!r} appears in the artifact but the kernel's block "
                    "does not declare it"
                )
                expected = list(source_value) if isinstance(source_value, tuple) else source_value
                assert value == expected, (key, name, value, expected)
                checked += 1
    assert checked > 100, f"only {checked} field(s) compared; this assertion went hollow"


def test_no_field_the_kernel_declared_is_dropped(artifact, engine_blocks) -> None:
    """The other direction: a declared field that never reaches the artifact is silence.

    Derived from the parse, not from a recorded number, so adding a block to a kernel cannot
    leave this test asserting yesterday's coverage.
    """
    from apps.runtime.mojo_inventory import discover_runtime_library_modules

    exported = {
        (module.import_path, function.name)
        for module in discover_runtime_library_modules(executable_only=True)
        for function in module.functions
    }
    emitted = {
        (module["name"], function["name"]): function["capability"]
        for module in artifact["modules"]
        for function in module["functions"]
    }
    for key, declared in engine_blocks.items():
        stated = {name: value for name, value in declared.items() if value is not None}
        if not stated or key not in exported:
            # No SDK-visible field, or not contract-exported: the SDK cannot describe it.
            continue
        assert key in emitted, f"{key} declares {sorted(stated)} but has no artifact entry"
        assert set(stated) == set(emitted[key]), (key, sorted(stated), sorted(emitted[key]))
    assert artifact["function_count"] == len(emitted)
    assert artifact["module_count"] == len(artifact["modules"])
    # A floor, so coverage cannot silently collapse to nothing; the exact number is derived
    # above rather than pinned here.
    assert artifact["function_count"] >= 50


def test_count_relations_never_travel_on_this_artifact(artifact) -> None:
    """One statement, one home. Relations ride the contract, beside the signature.

    Shipping them twice would create two statements that can disagree, and the runtime
    enforces from the contract.
    """
    assert "count_relations" not in EMITTED_FIELDS
    assert set(EMITTED_FIELDS) == set(CAPABILITY_FIELDS) - {"count_relations"}, (
        "the generator and the surface disagree about which fields this artifact carries; a "
        "new capability field would otherwise be silently unshippable"
    )
    for module in artifact["modules"]:
        for function in module["functions"]:
            assert "count_relations" not in function["capability"], (
                module["name"],
                function["name"],
            )


def test_no_entry_is_an_empty_block(artifact) -> None:
    """`{"capability": {}}` would read as "someone looked and declined every field"."""
    for module in artifact["modules"]:
        assert module["functions"], module["name"]
        for function in module["functions"]:
            assert function["capability"], (module["name"], function["name"])


# ── silence stays legible ─────────────────────────────────────────────────────


def test_a_function_with_no_block_is_undeclared_not_false() -> None:
    """The artifact covers a small fraction of the tree, and the rest must stay silent.

    Not `deterministic: False`, not an empty dict. `Undeclared.__bool__` raises, so a caller
    cannot accidentally read the silence as "no".
    """
    catalog = capabilities()
    undeclared_ref = next(
        ref
        for ref in catalog.search(module="stats").undeclared
        if not ref.has_block
    )
    record = catalog.describe("stats", undeclared_ref.function)
    assert record.has_block is False
    assert record.declared_fields() in ((), ("count_relations",))
    assert record.deterministic is UNDECLARED
    with pytest.raises(TypeError):
        bool(record.deterministic)
    payload = record.as_dict()
    assert "deterministic" not in payload
    assert "deterministic" in payload["undeclared_fields"]


def test_a_search_does_not_silently_omit_an_undeclared_function() -> None:
    """Every function in scope is a match, an explicit non-match, or reported as undeclared.

    A caller who saw only the matches would conclude a capability does not exist when it
    merely was not described — the reason `search()` returns `undeclared` at all. Checked over
    the whole real catalog, so a filter that quietly drops functions cannot hide in the tail.
    """
    catalog = capabilities()
    found = catalog.search(deterministic=True)
    matched = {(record.module, record.function) for record in found}
    reported = {(item.module, item.function) for item in found.undeclared}
    assert matched, "no function matched, so this test cannot distinguish silence from absence"
    assert reported, "nothing was reported as undeclared over a tree that is mostly undeclared"
    assert not matched & reported, "a function cannot be both a match and unjudgeable"
    assert all(item.missing == ("deterministic",) for item in found.undeclared)

    # Walk the inventory itself rather than trusting either list to be complete.
    unexplained: list[tuple[str, str]] = []
    for module in catalog.modules():
        for function in catalog.functions(module):
            key = (module, function)
            if key in matched or key in reported:
                continue
            record = catalog.describe(*key)
            # The only remaining legitimate reason to be in neither list: it declared the
            # field and the value did not match.
            if record.deterministic is not False:
                unexplained.append(key)
    assert not unexplained, (
        f"{len(unexplained)} function(s) were neither matched, reported as undeclared, nor "
        f"explicitly non-matching: {unexplained[:10]}"
    )
    assert found.scanned == sum(len(catalog.functions(m)) for m in catalog.modules())


def test_describe_still_raises_on_a_typo_rather_than_reading_as_absent() -> None:
    catalog = capabilities()
    with pytest.raises(CapabilityError) as unknown_module:
        catalog.describe("stats_but_misspelled", "compute_mean")
    assert unknown_module.value.code == "module_not_registered"
    with pytest.raises(CapabilityError) as unknown_function:
        catalog.describe("stats", "mean")  # the real export is compute_mean
    assert unknown_function.value.code == "function_not_registered"
    with pytest.raises(CapabilityError) as blank:
        catalog.describe("stats", "")
    assert blank.value.code == "invalid_arguments"


def test_a_hand_written_empty_block_reads_as_no_block() -> None:
    """Defence for a manifest this generator did not write.

    An empty block carries no more information than no block, so claiming `has_block=True`
    for it would tell a reader that someone considered and declined every field.
    """
    from algenta.capabilities import CapabilityCatalog

    class _Fn:
        def __init__(self, name: str) -> None:
            self.name = name
            self.count_relations = ()

    class _Mod:
        def __init__(self, path: str, names: tuple[str, ...]) -> None:
            self.import_path = path
            self.functions = tuple(_Fn(name) for name in names)

    catalog = CapabilityCatalog(
        contract_modules=(_Mod("m", ("a", "b")),),
        manifest_payload={
            "schema_version": 1,
            "modules": [
                {
                    "name": "m",
                    "functions": [
                        {"name": "a", "capability": {}},
                        {"name": "b", "capability": {"deterministic": None}},
                    ],
                }
            ],
        },
    )
    for name in ("a", "b"):
        record = catalog.describe("m", name)
        assert record.has_block is False, name
        assert record.declared_fields() == (), name
