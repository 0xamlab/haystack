"""Drift guard between the live FastAPI app and the committed schemas/openapi/openapi.yaml.

The spec used to be generated by booting the API and `curl`-ing /openapi.json by hand (see git
history of the Makefile's `openapi:` target) -- nothing forced anyone to actually do that after
changing a route, so the committed file could silently drift from what the app really serves.

This test calls the exact same `app.openapi()` the new in-process exporter
(scripts/openapi/export_openapi.py) uses -- via its `build_openapi_schema()` -- and compares the
resulting (method, path) operation set against what's currently committed. It fails on any
mismatch (a route added, removed, or renamed without regenerating the spec via `make openapi`),
and separately asserts the live path count hasn't collapsed below a regression floor.

Deliberately scoped to the OPERATION SET, not a full byte-for-byte schema diff: this repo's
current FastAPI/Pydantic pin (see mojo_env/pixi.toml) assigns component schemas non-
deterministically between "-Input"/"-Output" suffixed variants for models used in both a
request and a response context (observed directly: a live server booted from this exact,
unmodified commit produces a different component split than the file already committed from an
earlier regen of that SAME commit -- see this PR's description). That's a real but purely
cosmetic quirk (the split schemas are byte-identical to each other and to the unsplit original);
it is not the kind of drift this test exists to catch, and a byte-diff would flap on it forever.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from scripts.openapi.export_openapi import build_openapi_schema

_ROOT = Path(__file__).resolve().parent.parent
COMMITTED_SPEC_PATH = _ROOT / "schemas" / "openapi" / "openapi.yaml"
_METHODS = ("get", "post", "put", "patch", "delete", "options", "head", "trace")

# Real count observed 2026-08-24 by calling `app.openapi()` in-process on an unmodified checkout
# (cross-checked against a real live server's /openapi.json on the same commit): 216 paths / 238
# operations. The floor is set below that observed count, not at it, so this stays a guard
# against a REAL regression (a router failing to mount, a whole feature disappearing) rather
# than a number that needs bumping on every unrelated single-route addition or removal.
MIN_PATH_COUNT = 200


def _operation_pairs(schema: dict) -> set[tuple[str, str]]:
    pairs: set[tuple[str, str]] = set()
    for path, item in (schema.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for method in item:
            if method in _METHODS:
                pairs.add((method.upper(), path))
    return pairs


def _load_committed_spec() -> dict:
    assert COMMITTED_SPEC_PATH.exists(), (
        f"{COMMITTED_SPEC_PATH} is missing -- run `make openapi` to generate it."
    )
    return yaml.safe_load(COMMITTED_SPEC_PATH.read_text(encoding="utf-8"))


def test_committed_openapi_spec_matches_live_app_operations() -> None:
    """The actual drift this test exists to catch: a route added/removed/renamed in code
    without regenerating schemas/openapi/openapi.yaml via `make openapi`."""
    live_schema = build_openapi_schema()
    committed_schema = _load_committed_spec()

    live_ops = _operation_pairs(live_schema)
    committed_ops = _operation_pairs(committed_schema)

    live_only = live_ops - committed_ops
    committed_only = committed_ops - live_ops

    assert not live_only and not committed_only, (
        "schemas/openapi/openapi.yaml is out of date with the live FastAPI app. "
        f"Live but not committed: {sorted(live_only)}. "
        f"Committed but no longer live: {sorted(committed_only)}. "
        "Run `make openapi` and commit the regenerated file."
    )


def test_live_openapi_schema_path_count_meets_regression_floor() -> None:
    live_schema = build_openapi_schema()
    path_count = len(live_schema.get("paths") or {})
    assert path_count >= MIN_PATH_COUNT, (
        f"only {path_count} paths in the live OpenAPI schema (floor {MIN_PATH_COUNT}) -- this "
        "usually means a router failed to mount or app.openapi() broke, not a legitimate "
        "shrink; investigate before lowering the floor."
    )
