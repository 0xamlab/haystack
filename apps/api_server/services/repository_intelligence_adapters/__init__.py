_NON_ADAPTER_SUFFIXES = (
    "_analysis_support",
    "_primitives",
    "_support",
)

_DISCOVERED_ADAPTER_SUBMODULES = frozenset(
    path.stem
    for path in Path(__file__).resolve().parent.glob("*.py")
    if path.name != "__init__.py" and not path.stem.endswith(_NON_ADAPTER_SUFFIXES)
)

_AVAILABLE_SUBMODULES = frozenset(_LAZY_SUBMODULES | _DISCOVERED_ADAPTER_SUBMODULES)
__all__ = sorted(set(__all__) | _AVAILABLE_SUBMODULES)


def __getattr__(name: str) -> ModuleType:
    if name not in _AVAILABLE_SUBMODULES:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    module = import_module(f"{__name__}.{name}")
    globals()[name] = module
    return module


def __dir__() -> list[str]:
    return sorted(set(globals()) | _AVAILABLE_SUBMODULES)
