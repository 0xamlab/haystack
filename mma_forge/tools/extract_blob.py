#!/usr/bin/env python3
"""Extracts every `MTLB`-tagged Metal library blob from a `mojo build --emit object` output and
re-emits them as a symbol-free C byte array, ready to `clang -c` and `-Xlinker` into the pinned-
toolchain production binary. Never link the forge's own `.o` directly -- it carries `_main`/mojo-
runtime symbols that collide with the production binary's own. This script only copies the raw
Metal bitcode bytes, dropping everything else.

Usage:
    python3 extract_blob.py <forge.o> <out.c> --symbol algenta_mma_gemm_blob
    python3 extract_blob.py <forge.o> <out.c> --symbol algenta_mma_gemm_blob --check
"""
import argparse
import struct
import sys

MAGIC = b"MTLB"
LEN_OFFSET = 16
LEN_SIZE = 8


def find_blobs(data: bytes) -> list[bytes]:
    blobs = []
    i = 0
    while i + LEN_OFFSET + LEN_SIZE < len(data):
        if data[i : i + 4] == MAGIC:
            declared_len = struct.unpack_from("<Q", data, i + LEN_OFFSET)[0]
            if declared_len > LEN_OFFSET + LEN_SIZE and i + declared_len <= len(data):
                blobs.append(data[i : i + declared_len])
                i += declared_len
                continue
        i += 1
    return blobs


def render_c_source(symbol: str, blobs: list[bytes]) -> str:
    payload = b"".join(blobs)
    lines = [
        "/* GENERATED by mma_forge/tools/extract_blob.py -- do not hand-edit. */",
        "/* __attribute__((used)) is load-bearing: nothing in this translation unit reads the",
        " * array at runtime (only its sizeof, a compile-time constant), so an optimizing build",
        " * (this repo's shim is compiled -O2) would otherwise dead-strip the data entirely and",
        " * keep only the derived length -- verified by hitting exactly that bug empirically. */",
        f"static const unsigned char __attribute__((used)) {symbol}[] = {{",
    ]
    for offset in range(0, len(payload), 16):
        chunk = payload[offset : offset + 16]
        lines.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    lines.append(f"const unsigned long {symbol}_len = sizeof({symbol});")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("object_path")
    ap.add_argument("out_c_path")
    ap.add_argument("--symbol", required=True)
    ap.add_argument("--check", action="store_true", help="verify out_c_path matches, don't write")
    args = ap.parse_args()

    data = open(args.object_path, "rb").read()
    blobs = find_blobs(data)
    if not blobs:
        print(f"extract_blob: no MTLB blobs found in {args.object_path}", file=sys.stderr)
        return 1
    rendered = render_c_source(args.symbol, blobs)

    if args.check:
        try:
            existing = open(args.out_c_path).read()
        except FileNotFoundError:
            print(f"extract_blob: --check: {args.out_c_path} does not exist", file=sys.stderr)
            return 1
        if existing != rendered:
            print(f"extract_blob: --check: {args.out_c_path} is stale", file=sys.stderr)
            return 1
        print(f"extract_blob: --check: {args.out_c_path} matches ({len(blobs)} blob(s))")
        return 0

    with open(args.out_c_path, "w") as f:
        f.write(rendered)
    print(f"extract_blob: wrote {args.out_c_path} ({len(blobs)} blob(s), {len(open(args.object_path,'rb').read())} byte object)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
